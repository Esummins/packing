"""A250: results/family250.md from the lanes' jsonl rows, the ILP count and the corpus test.
Rerun at any time -- the lanes are resumable, so the numbers are 'the effort so far'."""
import glob
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ATT = os.path.abspath(os.path.join(HERE, '..'))
ROOT = os.path.abspath(os.path.join(ATT, '..', '..'))
sys.path.insert(0, HERE)


def rows(tag):
    p = os.path.join(ATT, 'results', 'fam250_%s.jsonl' % tag)
    if not os.path.exists(p):
        return []
    out = []
    for line in open(p):
        if line.strip():
            try:
                out.append(json.loads(line))
            except Exception:                                     # noqa
                pass
    return out


def recheck(rs, cap=400):
    """re-verify every candidate that met its rows with the CURRENT verify250 (the lanes may have
    been started with an older one), and overwrite its `cert`."""
    import verify250 as V
    out = []
    for r in rs:
        if not r.get('target_met') or 'z' not in r or len(out) >= cap:
            continue
        c = V.certify_z(r['z'])
        r['cert'] = {k: v for k, v in c.items() if k not in ('sure_meeters', 'witness_families')}
        out.append({'rid': r['rid'], 's': r['s'], 'cert': r['cert'],
                    'witness_families': c['witness_families'][:3]})
    return out


def lane_line(tag, rs):
    if not rs:
        return '| %s | 0 | -- | -- | -- | -- |' % tag
    tgt = [r for r in rs if r.get('target_met')]
    cert = [r for r in tgt if r.get('cert', {}).get('FAMILY_STUCK')]
    secs = sum(r.get('secs', 0) for r in rs)
    return '| %s (kmax %d, %s) | %d | %.1f h | %d | %s | %s |' % (
        tag, rs[0].get('maxfam', 0), rs[0].get('mode', '?'), len(rs), secs / 3600.0, len(tgt),
        ('%.6f' % min(r['s'] for r in tgt)) if tgt else 'none',
        ('%.6f' % min(r['cert']['s_cert'] for r in cert)) if cert else 'NONE')


def residual_table(rs):
    best = {}
    for r in rs:
        s = r.get('side')
        if s is None or 'residual' not in r:
            continue
        if s not in best or r['residual'] < best[s][0]:
            best[s] = (r['residual'], r.get('min_excess_float'), r.get('rid'))
    return best


def main():
    cj = json.load(open(os.path.join(ATT, 'results', 'count250.json')))
    tags = sorted({os.path.basename(p)[7:-6]
                   for p in glob.glob(os.path.join(ATT, 'results', 'fam250_*.jsonl'))})
    data = {t: rows(t) for t in tags}
    rech = []
    for t in tags:
        rech += recheck(data[t])
    if rech:
        with open(os.path.join(ATT, 'results', 'recheck250.jsonl'), 'w') as fh:
            for r in rech:
                fh.write(json.dumps(r) + chr(10))
    L = []
    L.append('# A250 -- FAMILY-STUCK: the search, the count, the corpus')
    L.append('')
    L.append('Generated by `code/summarise250.py` on %s.  FAMILY-STUCK: every family Pi of '
             'pairwise disjoint border cells' % time.strftime('%Y-%m-%d %H:%M'))
    L.append('has `|M(Pi)| > |Pi|` (Lemma CELLS exchanges as soon as `|M(Pi)| <= |Pi|`).  A244\'s '
             'TWELVE-STUCK is the rows `|Pi| = 1` only.')
    L.append('')
    L.append('## 1. The count (exact, `count250.py`)')
    L.append('')
    L.append('| level | s in [3, 4) | s >= 4 |')
    L.append('| --- | --- | --- |')
    lab = {1: '`|Pi| <= 1` (TWELVE-STUCK)', 2: '`|Pi| <= 2` (dominoes)', 3: '`|Pi| <= 3`',
           4: '`|Pi| <= 4`', 6: '`|Pi| <= 6`', 8: '`|Pi| <= 8`', 12: 'every family (FAMILY-STUCK)'}
    for k in (1, 2, 3, 4, 6, 8, 12):
        get = {r['regime']: r['n_min'] for r in cj['ladder']
               if r['kmax'] == k and not r.get('layer') and not r.get('corner_only')}
        L.append('| %s | %s | %s |' % (lab[k], get.get('below4'), get.get('at4')))
    for r in cj['ladder']:
        if r.get('layer'):
            L.append('| %s, %s, kmax %d | %s | %s |' % (
                r['regime'], r['layer'], r['kmax'],
                r['n_min'] if r['regime'] == 'below4' else '',
                r['n_min'] if r['regime'] == 'at4' else ''))
    L.append('')
    L.append('n_min is the minimum number of squares an INCIDENCE STRUCTURE needs: an ILP over the '
             'PROJECTION catalogue (a square meets')
    L.append('cells of one five-cell corner neighbourhood only, A247 [T]) with '
             'NOT-SELF-SUFFICIENT [T, A246] and TWO-FAR [T, A247].')
    L.append('Any family-stuck packing gives a feasible point, so n_min is a valid lower bound on '
             'n for every n and every packing.')
    L.append('')
    L.append('**13 > 11 at every side >= 4** -- no packing of eleven unit squares at or above side '
             '4 is family-stuck, while A244 certifies 488')
    L.append('TWELVE-stuck ones from 4.000010 to 4.5.  Below 4 the count reaches only 9 <= 11: it '
             'does NOT close the window.')
    L.append('')
    st = cj.get('structure', [])
    if st:
        L.append('The shape of the smallest structures the count allows (min/max of each '
                 'functional over all structures of that size):')
        L.append('')
        L.append('| n | free squares | 5-cell squares | meeters of BL | cross-corner squares | '
                 'ADJ suppliers |')
        L.append('| --- | --- | --- | --- | --- | --- |')
        for r in st:
            L.append('| %d | %s | %s | %s | %s | %s |' % (
                r['n'], r['free_squares'], r['five_cell_squares'], r['meeters_of_BL'],
                r['cross_corner_squares'], r['adj_suppliers']))
        L.append('')
    L.append('## 2. The corpus (exact in `verify250`, float scan in `count250 --what corpus`)')
    L.append('')
    L.append('| corpus | n | sides | twelve-stuck | pair-stuck | family-stuck |')
    L.append('| --- | --- | --- | --- | --- | --- |')
    for k, v in cj.get('corpus', {}).items():
        L.append('| %s | %d | %.6f .. %.6f | %d | %d | %d |' % (
            k, v['n'], v['sides'][0], v['sides'][1], v['twelve_stuck'], v['pair_stuck'],
            v['family_stuck']))
    L.append('')
    for k, v in cj.get('corpus', {}).items():
        L.append('* %s stuck dominoes (a corner domino met by exactly two squares in total, '
                 'counting every occurrence): %s' % (k, v['stuck_dominoes']))
    L.append('')
    L.append('## 3. The search (`search250.py`, resumable; `run250.sh laneA|laneB`)')
    L.append('')
    L.append('| lane | jobs | cpu | target met | least side at target | least CERTIFIED '
             'family-stuck side |')
    L.append('| --- | --- | --- | --- | --- | --- |')
    for t in tags:
        L.append(lane_line(t, data[t]))
    L.append('')
    res = {}
    for t in tags:
        for s, v in residual_table(data[t]).items():
            if s not in res or v[0] < res[s][0]:
                res[s] = v
    if res:
        L.append('Best residual per side (the fixed-side lanes; residual 0 = the rows are met with '
                 'margin delta at that side):')
        L.append('')
        L.append('| side | best residual | worst family excess |')
        L.append('| --- | --- | --- |')
        for s in sorted(res):
            L.append('| %.6f | %.3e | %s |' % (s, res[s][0], res[s][1]))
        L.append('')
    allr = [r for t in tags for r in data[t]]
    cert = [r for r in allr if r.get('cert', {}).get('FAMILY_STUCK')]
    L.append('**No candidate anywhere is FAMILY-STUCK**: %d of %d jobs met the rows imposed '
             '(|Pi| <= maxfam) and %d certified' % (
                 sum(1 for r in allr if r.get('target_met')), len(allr), len(cert)))
    L.append('FAMILY-STUCK exactly (re-verified with the current `verify250` into '
             '`results/recheck250.jsonl`).  Every candidate that met the rows was verified in '
             'interval arithmetic (containment,')
    L.append('pairwise interior-disjointness, and the family condition over EVERY disjoint family '
             'at the certified side).')
    p = os.path.join(ATT, 'results', 'family250.md')
    open(p, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote', p, len(L), 'lines')


if __name__ == '__main__':
    main()
