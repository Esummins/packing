"""A256 -- the progress page (A225's pstats block) for the trump5 passes: results/progress.md.

Read from results/trump5passes256.jsonl ONLY (the shard rows run256 / worker256 append) plus A212's pass-1 verdicts
(results/triage256.json) as the baseline.  A page is CLOSED when its merged certificate has no start node left;
that is what queue256.py answers, so the page count here is the queue's own count, recomputed cheaply.
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
A211 = os.path.join(ROOT, "attempts", "A211-coarse-tree", "code")
RES = os.path.abspath(os.path.join(HERE, "..", "results", "trump5passes256.jsonl"))
TRIAGE = os.path.abspath(os.path.join(HERE, "..", "results", "triage256.json"))
OUT = os.path.abspath(os.path.join(HERE, "..", "results", "progress.md"))
sys.path.insert(0, A211)


def jl(p):
    out = []
    if os.path.exists(p):
        for ln in open(p, encoding="utf-8", errors="replace"):
            ln = ln.strip()
            if ln:
                try:
                    out.append(json.loads(ln))
                except Exception:                                  # noqa: BLE001
                    pass
    return out


def main():
    rows = jl(RES)
    tri = json.load(open(TRIAGE, encoding="utf-8")) if os.path.exists(TRIAGE) else dict(rows=[], counts={})
    alive0 = [r["nid"] for r in tri["rows"] if r["a212"] == "ALIVE"]
    by = {}
    for r in rows:
        k = (r.get("nid"), r.get("pad"))
        by.setdefault(k, []).append(r)
    shards = [r for r in rows if r.get("shard")]
    killed = [r for r in shards if r.get("killed")]
    dead_starts, alive_starts, secs = 0, 0, 0.0
    for r in shards:
        secs += float(r.get("seconds") or 0.0)
        for s in (r.get("start_runs") or []):
            if s.get("verdict") == "DEAD":
                dead_starts += 1
            else:
                alive_starts += 1
    pages = sorted(set(r.get("nid") for r in shards))
    L = ["# A256 -- trump5 passes: progress  (regenerated by code/progress256.py at %s)" % time.strftime("%Y-%m-%d %H:%M:%S"),
         "",
         "Population: A212's 149 trump5 nodes -- 84 ALIVE, 65 DEAD at pad 0 (pass 1, 2026-09-14/15, one 1,800 s wall",
         "each, before A220 / A221 / A224 / A228 / A229 / A230).  Triage (results/triage256.json): (a) %d, (b) %d --"
         % (tri.get("counts", {}).get("a", 0), tri.get("counts", {}).get("b", 0)),
         "no node of the population admits a contracted Trump image, so every leaf rule of the chain applies and the",
         "tube leaves (Lemma TUBE-LEAF / Lemma TUBE-KILL) have an empty domain here (notes/trump5_closure.md s.3).",
         "",
         "## Pass rows (results/trump5passes256.jsonl)",
         "",
         "| what | value |",
         "|---|---|",
         "| shard rows | %d |" % len(shards),
         "| pages touched | %d of %d alive |" % (len(pages), len(alive0)),
         "| start nodes DEAD this campaign | %d |" % dead_starts,
         "| start nodes still ALIVE / undecided | %d |" % alive_starts,
         "| crashed / wall-killed shards (A228 rows) | %d |" % len(killed),
         "| CPU seconds in shards | %.0f |" % secs,
         ""]
    if shards:
        L += ["## Last 20 shards", "", "| page | pad | start | verdict | s | rc |", "|---|---|---|---|---|---|"]
        for r in shards[-20:]:
            L.append("| %s | %s | %s | %s | %s | %s |" % (
                r.get("nid"), r.get("pad"), ",".join(r.get("start_filter") or []), r.get("verdict"),
                round(float(r.get("seconds") or 0), 0), r.get("rc", 0)))
        L.append("")
    L += ["## Stop / resume", "",
          "    touch attempts/A256-trump5-passes/logs/STOP_LOOP   # the loop exits at the top of the next pass",
          "    touch attempts/A256-trump5-passes/logs/STOP        # each worker exits after its current start node",
          "    rm -f attempts/A256-trump5-passes/logs/STOP*       # then relaunch code/loop256.sh with the same line",
          ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print("   -> %s (%d shard rows, %d pages)" % (os.path.relpath(OUT, ROOT).replace("\\", "/"), len(shards), len(pages)))


if __name__ == "__main__":
    main()
