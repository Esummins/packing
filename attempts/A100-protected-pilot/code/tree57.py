"""
A57 rung-3 shadow tree: ONE-LEVEL sub-stratification of a shadow stratum (k5_11 / k5_16),
interior-first, breadth-first, easiest-first, resumable, checkpointed.

Branch (A54 substrat semantics, unchanged):
  parent = the k pinned slot squares, budget 11-k.
  zone Z (rectangle of centres) x [0,90] is covered by closed boxes {B_i}; children are
     NO   : parent + NO-family (Z x [0,90])                 budget 11-k      (stays at budget)
     YES_i: parent + core box B_i                           budget 11-k-1
  "no square centre in Z" OR "some square has (centre,theta) in some B_i" is exhaustive
  (the cover is closed and vacuous boxes contain no admissible placement), so the parent
  stratum is EMPTY as soon as every child carries an exact certificate.
  The sole arbiter of a kill is verify_case.py on the exact rational certificate (A54 S0):
  tau < budget is NOT a kill and tau >= budget is NOT a survival.

A57 additions over A54's substrat.py:
  * theta subdivision uniform in t = tan(theta/2), so the core half-side
    a = (1/2 - hd)/(1 + (t1-t0)) is UNIFORM over the cover (A24 (iii) wants a >= 0.31..0.35;
    A54's degree-uniform cover gave a = 0.022..0.043 in the interior/side zones).
  * easiest-first ordering: children farthest from Trump's ghost placements first
    (A54 S1: the stragglers' LP optima are Trump's ghost re-decorated, so the hard children
    are the ones sitting on his squares).
  * sibling COLUMN folding (A55/k3_ext E3): atoms generated by solved siblings are folded
    into the warm start of the next child.  Columns only -- rows are never folded (memory)
    and rows are never pruned inside a child solve.
  * fully resumable: one jsonl record per finished child, one node json per child, a
    progress json rewritten after every child.  Re-running the same shard skips finished
    children and re-folds their atoms.

Canary: trump5 is never a target; every child is checked with substrat.trump_realizes and,
if Trump's packing realises it, it is recorded and NEVER certified.
"""
import argparse, json, math, os, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.abspath(os.path.join(HERE, ".."))
A53 = os.path.abspath(os.path.join(BASE, "..", "A53-simple-strata"))
sys.path.insert(0, HERE)
import caselp
from caselp import Box, NoFam, Hyp, solve_node
from run_skel import S0F
from substrat import zones, trump_realizes
from pinguard import classify
from warm57 import merged_warm

S_RAT = "969271/250000"


# ------------------------------------------------------------------ cover
def theta_edges(nth):
    """theta boundaries uniform in t = tan(theta/2) over [0,1] -> [0,90] degrees."""
    return [math.degrees(2.0 * math.atan(k / nth)) for k in range(nth + 1)]


def cover(rect, s, w, nth, a_min, max_split=3):
    """closed cover of rect x [0,90] by boxes of centre-width ~w and t-uniform theta cells.
    Vacuous boxes are dropped (sound: they contain no admissible placement).  Boxes whose
    rational core is empty or smaller than a_min are bisected up to max_split times."""
    x0, x1, y0, y1 = rect
    nx = max(1, int(math.ceil((x1 - x0) / w)))
    ny = max(1, int(math.ceil((y1 - y0) / w)))
    te = theta_edges(nth)
    todo = [Box(x0 + (x1 - x0) * i / nx, x0 + (x1 - x0) * (i + 1) / nx,
                y0 + (y1 - y0) * j / ny, y0 + (y1 - y0) * (j + 1) / ny,
                te[k], te[k + 1])
            for i in range(nx) for j in range(ny) for k in range(nth)]
    out, bad = [], []
    for _ in range(max_split + 1):
        nxt = []
        for b in todo:
            if b.vacuous(s):
                continue
            c = b.core()
            if c is not None and float(c.a) >= a_min:
                out.append(b)
            else:
                nxt.append(b)
        if not nxt:
            break
        todo = [h for b in nxt for h in b.split()]
    else:
        for b in todo:
            if b.vacuous(s):
                continue
            if b.core() is not None:
                out.append(b)       # keep: sound, just weaker than a_min
            else:
                bad.append(b)       # NOT sound to keep: no rational core
    return out, bad, (nx, ny, nth)


# ------------------------------------------------------------------ ordering
def ghost_placements():
    p = os.path.abspath(os.path.join(BASE, "..", "A03-upper-reconstruct", "trump11_float.json"))
    X = json.load(open(p))["X"]
    return [(x, y, math.tan((math.degrees(th) % 90.0) * math.pi / 360.0)) for (x, y, th) in X]


def ghost_dist(b, G):
    """distance from a box's midpoint to the nearest Trump placement in (x, y, 2t)."""
    cx, cy = 0.5 * (b.x0 + b.x1), 0.5 * (b.y0 + b.y1)
    t = 0.5 * (math.tan(math.radians(b.th0) / 2) + math.tan(math.radians(b.th1) / 2))
    return min(math.sqrt((cx - x) ** 2 + (cy - y) ** 2 + (2 * (t - tt)) ** 2) for (x, y, tt) in G)


# ------------------------------------------------------------------ children
def build_children(name, zone, w, nth, cw, a_min):
    slots = [tuple(p) for p in json.load(open(os.path.join(A53, "results", "name_to_slots.json")))[name]]
    pins = [Box(x, x, y, y, 0.0, 0.0) for (x, y) in slots]
    rect = zones(S0F, cw)[zone]
    boxes, bad, grid = cover(rect, S0F, w, nth, a_min)
    G = ghost_placements()
    kids = [dict(id=f"{name}_{zone}_NO", kind="NO", box=None, score=1e9,
                 hyp=Hyp(pins, [NoFam(rect[0], rect[1], rect[2], rect[3], [(0.0, 90.0)])]),
                 budget=11 - len(slots), a=None)]
    scored = sorted(boxes, key=lambda b: -ghost_dist(b, G))     # easiest (farthest) first
    for i, b in enumerate(scored):
        st, info = classify(b, pins, slots)
        kids.append(dict(id=f"{name}_{zone}_Y{i:04d}", kind="YES", box=b,
                         score=ghost_dist(b, G), a=float(b.core().a), pin=st, pin_info=info,
                         hyp=Hyp(pins + [b], []), budget=11 - len(slots) - 1))
    return kids, bad, slots, rect, grid


# ------------------------------------------------------------------ EPS_CORE ladder (T11)
def run_eps_ladder(node_path, kid, a, certdir, log, eps=(5e-4, 2e-4, 5e-5)):
    """A child that converges to tau >= budget is normally being held there by caselp's 2e-3
    core shell, which `verify_case.py` (exact exemption) does not require.  Re-solve at smaller
    EPS_CORE -- strictly fewer rows, so tau can only fall -- and certify.  Sound in the only way
    that matters: the arbiter is unchanged, so a shell that WAS needed just makes the exact
    verification FAIL."""
    res0 = json.load(open(node_path))
    warm2 = dict(atoms=[(x[0], x[1]) for x in res0.get("atoms_all", [])], rows=[])
    out = dict(eps_ladder=[])
    try:
        for e in eps:
            caselp.EPS_CORE = e
            t0 = time.time()
            r = solve_node(S0F, kid["hyp"], kid["budget"], sym_kind="C1", warm=warm2,
                           time_limit=a.time_limit, max_iter=900, out=None, log=log,
                           prune=0, prune_cols=3, col_stop_iter=10 ** 6, col_stop_cov=1.002,
                           max_cols_add=400, max_rows_add=2000, fine_slack=0.05, alternate=True)
            r["eps_core"] = e
            step = dict(eps_core=e, tau=r["tau"], eta=r["tau"] - kid["budget"],
                        conv=r["converged"], lp_s=round(time.time() - t0, 1))
            if r["tau"] < kid["budget"]:
                np2 = node_path.replace(".json", f"_eps{e:g}.json")
                json.dump(r, open(np2, "w"))
                cert_out = os.path.join(certdir, f"{kid['id']}_eps{e:g}.json")
                cmd = [sys.executable, os.path.join(HERE, "certify.py"), np2, "--s_rat", S_RAT,
                       "--rounds", str(a.rounds), "--jobs", str(a.jobs), "--depth", str(a.depth),
                       "--time_limit", str(a.cert_time), "--out", cert_out, "--scale", "0",
                       "--scale_cap", f"{a.scale_cap:.5f}", "--max_w", "64", "--loop_cols"]
                p = subprocess.run(cmd, capture_output=True, text=True)
                log(p.stdout[-2000:])
                step["cert"] = "PASS" if p.returncode == 0 else f"FAIL(rc={p.returncode})"
                out["eps_ladder"].append(step)
                if p.returncode == 0:
                    open(cert_out + ".PASS", "w").write("ok")
                    out.update(cert="PASS", cert_path=cert_out, eps_core_used=e,
                               tau_ladder=r["tau"], eta_ladder=r["tau"] - kid["budget"])
                    return out
            else:
                out["eps_ladder"].append(step)
    finally:
        caselp.EPS_CORE = 2e-3          # never leak the shrunken shell to the next child
    out["cert"] = ("ALIVE-at-LP after EPS_CORE ladder"
                   if all(s.get("cert") is None for s in out["eps_ladder"])
                   else "FAIL(eps ladder exhausted)")
    return out


# ------------------------------------------------------------------ driver
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--zone", default="interior")
    ap.add_argument("--cw", type=float, default=0.6)
    ap.add_argument("--w", type=float, default=0.15, help="centre-cell width")
    ap.add_argument("--nth", type=int, default=8, help="theta cells, uniform in t")
    ap.add_argument("--a_min", type=float, default=0.34)
    ap.add_argument("--shard", default="0/1")
    ap.add_argument("--tag", default="L1")
    ap.add_argument("--time_limit", type=float, default=240, help="child LP time limit")
    ap.add_argument("--no_time_limit", type=float, default=900, help="LP time limit of the NO child")
    ap.add_argument("--cert_time", type=float, default=240)
    ap.add_argument("--rounds", type=int, default=2)
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--depth", type=int, default=56)
    ap.add_argument("--scale_cap", type=float, default=1.40)
    ap.add_argument("--max_rows", type=int, default=30000, help="cap on warm rows (sound: fewer rows only risk FAIL)")
    ap.add_argument("--fold_cap", type=int, default=14000, help="cap on the folded sibling column pool")
    ap.add_argument("--max_children", type=int, default=10 ** 6)
    ap.add_argument("--wall_seconds", type=float, default=10 ** 9)
    ap.add_argument("--eps_ladder", action="store_true",
                    help="T11: on tau >= budget, retry at smaller EPS_CORE before giving up "
                         "(sound but empirically weak: the shell rows are usually genuinely "
                         "required by the exact verifier -- see notes T11)")
    ap.add_argument("--plan_only", action="store_true")
    ap.add_argument("--lp_only", action="store_true")
    a = ap.parse_args()

    kids, bad, slots, rect, grid = build_children(a.name, a.zone, a.w, a.nth, a.cw, a.a_min)
    si, sn = map(int, a.shard.split("/"))
    key = f"{a.name}_{a.zone}_{a.tag}"
    outdir = os.path.join(BASE, "results", "tree", key)
    certdir = os.path.join(BASE, "certs", "tree", key)
    os.makedirs(outdir, exist_ok=True); os.makedirs(certdir, exist_ok=True)

    if a.plan_only:
        aa = [k["a"] for k in kids if k["a"] is not None]
        print(json.dumps(dict(name=a.name, zone=a.zone, rect=rect, grid=grid, children=len(kids),
                              yes=len(kids) - 1, uncoverable=len(bad),
                              a_min=min(aa) if aa else None, a_max=max(aa) if aa else None,
                              canary=[k["id"] for k in kids if trump_realizes(k["hyp"], slots)]), indent=1))
        return
    if bad:
        print(f"FATAL: {len(bad)} boxes with no rational core -- cover NOT complete", flush=True)
        sys.exit(4)

    mine = [k for i, k in enumerate(kids) if i % sn == si][:a.max_children]
    summary = os.path.join(BASE, "results", f"tree_{key}_s{si}.jsonl")
    progress = os.path.join(BASE, "progress", f"{key}_s{si}.json")
    logf = open(os.path.join(BASE, "logs", f"{key}_s{si}.log"), "a", buffering=1)
    def log(*x):
        print(*x, file=logf, flush=True)

    done = {}
    if os.path.exists(summary):
        for line in open(summary):
            try:
                r = json.loads(line)
                done[r["id"]] = r       # ALIVE records included: deepen.py owns them (depth 2)
            except Exception:
                pass

    warm, used = merged_warm(a.name, max_rows=a.max_rows)
    pool = list(warm["atoms"]); seen = {(round(p[0], 7), round(p[1], 7)) for p in pool}
    log(f"=== A57 {key} shard {si}/{sn} {time.strftime('%Y-%m-%d %H:%M:%S')} "
        f"children={len(mine)} done={len([k for k in mine if k['id'] in done])} "
        f"warm={len(pool)} atoms {len(warm['rows'])} rows from {used}")

    # re-fold the columns of children finished in an earlier run
    for k in mine:
        np_ = os.path.join(outdir, f"{k['id']}.json")
        if k["id"] in done and os.path.exists(np_) and len(pool) < a.fold_cap:
            try:
                for at in json.load(open(np_)).get("atoms_all", []):
                    kk = (round(at[0], 7), round(at[1], 7))
                    if kk not in seen:
                        seen.add(kk); pool.append((at[0], at[1]))
            except Exception:
                pass
    log(f"    folded pool = {len(pool)} atoms")

    t_start = time.time()
    stats = dict(key=key, shard=a.shard, total=len(mine), done=0, killed=0, alive_lp=0,
                 cert_fail=0, canary=0, skipped=len(done), started=time.strftime("%Y-%m-%d %H:%M:%S"))

    def flush():
        stats["elapsed_s"] = round(time.time() - t_start, 1)
        stats["updated"] = time.strftime("%Y-%m-%d %H:%M:%S")
        stats["pool_atoms"] = len(pool)
        json.dump(stats, open(progress, "w"), indent=1)

    flush()
    for kid in mine:
        if kid["id"] in done:
            continue
        if time.time() - t_start > a.wall_seconds:
            log("    wall_seconds reached; stopping cleanly"); break
        node_path = os.path.join(outdir, f"{kid['id']}.json")
        rec = dict(id=kid["id"], kind=kid["kind"], budget=kid["budget"], zone=a.zone,
                   a=kid["a"], ghost_dist=round(kid["score"], 5))
        if kid["kind"] == "YES":
            rec["box"] = kid["box"].to_json()
        canary = trump_realizes(kid["hyp"], slots)
        rec["trump_realizes"] = canary
        rec["pin"] = kid.get("pin")
        rec["pin_info"] = kid.get("pin_info")
        if kid.get("pin") == "contradictory":
            # every square with (centre, theta) in B overlaps a pinned square and is not it
            rec.update(tau=None, eta=None, cert="KILL-BY-LOGIC (core meets pin core)",
                       lp_seconds=0.0)
            stats["killed"] += 1; stats["logic_kill"] = stats.get("logic_kill", 0) + 1
            stats["done"] += 1
            log("    " + json.dumps(rec))
            with open(summary, "a") as f:
                f.write(json.dumps(rec) + chr(10))
            flush(); continue
        if kid.get("pin") == "parent":
            # B may be witnessed by the pin itself: budget 11-k-1 would be UNSOUND (pinguard)
            rec.update(tau=None, eta=None, lp_seconds=0.0,
                       cert="UNSOUND-AT-REDUCED-BUDGET (box realises a pin; = parent node)")
            stats["parent_box"] = stats.get("parent_box", 0) + 1
            stats["done"] += 1
            log("    " + json.dumps(rec))
            with open(summary, "a") as f:
                f.write(json.dumps(rec) + chr(10))
            flush(); continue
        t0 = time.time()
        if os.path.exists(node_path):
            res = json.load(open(node_path))
        else:
            tl = a.no_time_limit if kid["kind"] == "NO" else a.time_limit
            log(f"[{time.strftime('%H:%M:%S')}] LP {kid['id']} budget={kid['budget']} "
                f"a={kid['a']} gd={kid['score']:.3f} pool={len(pool)}")
            res = solve_node(S0F, kid["hyp"], kid["budget"], sym_kind="C1",
                             warm=dict(atoms=pool, rows=warm["rows"]),
                             time_limit=tl, max_iter=900, out=None, log=log,
                             prune=0, prune_cols=3, col_stop_iter=10 ** 6, col_stop_cov=1.002,
                             max_cols_add=400, max_rows_add=2000, fine_slack=99.0, alternate=True)
            res["parent"] = a.name; res["child_id"] = kid["id"]
            json.dump(res, open(node_path, "w"))
        rec.update(tau=res["tau"], converged=res["converged"], minmass=res["minmass"],
                   maxcov=res["maxcov"], eta=res["tau"] - kid["budget"],
                   lp_seconds=round(time.time() - t0, 1),
                   scale_ceiling=(kid["budget"] / res["tau"]) if res["tau"] > 0 else None)
        if len(pool) < a.fold_cap:
            for at in res.get("atoms_all", []):
                kk = (round(at[0], 7), round(at[1], 7))
                if kk not in seen:
                    seen.add(kk); pool.append((at[0], at[1]))

        if canary:
            rec["cert"] = "CANARY (Trump-realizable: never certified)"; stats["canary"] += 1
        elif a.lp_only:
            rec["cert"] = "not attempted (--lp_only)"
        elif res["tau"] >= kid["budget"]:
            # T11: tau = budget is normally the 2e-3 core shell, which the EXACT verifier does not
            # need.  Shrink EPS_CORE (sound: fewer rows, and a wrong choice can only FAIL) and retry.
            lad = (run_eps_ladder(node_path, kid, a, certdir, log) if a.eps_ladder
                   else dict(cert="ALIVE-at-LP (tau >= budget: certification refused) "
                                  "-> queued for depth 2 (deepen.py)"))
            rec.update(lad)
            if rec["cert"] == "PASS":
                stats["killed"] += 1; stats["ladder_kill"] = stats.get("ladder_kill", 0) + 1
            elif rec["cert"].startswith("ALIVE"):
                stats["alive_lp"] += 1
            else:
                stats["cert_fail"] += 1
        else:
            cert_out = os.path.join(certdir, f"{kid['id']}.json")
            cmd = [sys.executable, os.path.join(HERE, "certify.py"), node_path, "--s_rat", S_RAT,
                   "--rounds", str(a.rounds), "--jobs", str(a.jobs), "--depth", str(a.depth),
                   "--time_limit", str(a.cert_time), "--out", cert_out, "--scale", "0",
                   "--scale_cap", f"{a.scale_cap:.5f}", "--max_w", "64", "--loop_cols"]
            t1 = time.time()
            p = subprocess.run(cmd, capture_output=True, text=True)
            log(p.stdout[-3000:])
            ok = (p.returncode == 0)
            rec["cert"] = "PASS" if ok else f"FAIL(rc={p.returncode})"
            rec["cert_seconds"] = round(time.time() - t1, 1)
            rec["cert_path"] = cert_out if ok else None
            if ok:
                open(cert_out + ".PASS", "w").write("ok"); stats["killed"] += 1
            else:
                stats["cert_fail"] += 1
        stats["done"] += 1
        log("    " + json.dumps(rec))
        with open(summary, "a") as f:
            f.write(json.dumps(rec) + "\n")
        flush()
    stats["finished"] = time.strftime("%Y-%m-%d %H:%M:%S")
    flush()
    log("shard done " + json.dumps(stats))
    print(json.dumps(stats), flush=True)


if __name__ == "__main__":
    main()
