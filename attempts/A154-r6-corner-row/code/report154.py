"""A154 -- assemble the in-vitro tables and the price from results/.  Writes notes/tables.md
and results/price154.json.  No LP, no verifier, read-only outside A154."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import a154lib as L  # noqa: E402

# A115 T3 / A99 measured per-cell values for the k0_00 tree
WORTH_L1 = (43.2, 100.3)     # CPU-h removed by one CERTIFIED level-1 kill
WORTH_L2 = (5.41, 12.54)
K0_FRONTIER = (9341.0, 21661.0)
K0_ROW = 12000.0
K0_ROW_AFTER_A141 = (9400.0, 10900.0)
N_L1 = 216
PROTECTED_TIER = (2900.0, 6300.0, 3800.0)


def rows(path):
    if not os.path.exists(path):
        return []
    out = []
    for ln in open(path, encoding="utf-8"):
        ln = ln.strip()
        if ln:
            out.append(json.loads(ln))
    return out


def md_table(hdr, body):
    s = "| " + " | ".join(hdr) + " |\n|" + "|".join(["---"] * len(hdr)) + "|\n"
    for r in body:
        s += "| " + " | ".join(str(x) for x in r) + " |\n"
    return s


def fmt(x, n=4):
    return "—" if x is None else ("%.*f" % (n, x))


def main():
    scr = {r["nid"] + "|" + r["group"]: r for r in rows(os.path.join(L.RES, "screen154.jsonl"))}
    lps = rows(os.path.join(L.RES, "lp154.jsonl"))
    last = {}
    for r in lps:
        last[(r["nid"], r["group"], r["use_id"])] = r
    allscr = rows(os.path.join(L.RES, "screenall154.jsonl"))
    summ = json.load(open(os.path.join(L.RES, "screenall154_summary.json")))
    band = json.load(open(os.path.join(L.RES, "bandeep154.json")))
    cls = json.load(open(os.path.join(L.RES, "classrow154.json")))

    out = ["# A154 — in-vitro tables (generated by `code/report154.py`)", ""]

    for g, title in (("eleven", "The eleven converged-alive k0_00 cells (EXACT A135 cores + (R6))"),
                     ("nearmiss", "A141 near-miss cells (stock cores + (R6))"),
                     ("rand_l1", "Random open level-1 cells (stock cores + (R6))"),
                     ("trump5", "A60 alive trump5 nodes (stock cores + the TL-only class row)")):
        body = []
        for k, r in scr.items():
            if not k.endswith("|" + g):
                continue
            lp = last.get((r["nid"], g, False))
            body.append([r["nid"], r.get("level") or "—", r["B"], fmt(r["c_stored"], 3),
                         "yes" if r["screen"] == "PROVED-USELESS" else
                         ("cand" if r["screen"].startswith("CANDIDATE") else "diag"),
                         # tau0/eta0 must be the MATCHED baseline: for the eleven the LP arm uses
                         # A140's exact-core tau, not the A115 axis-core record the screen reads.
                         fmt(lp["tau0"] if lp else r["tau0"]),
                         fmt(lp["eta0"] if lp else r["eta0"], 6),
                         fmt(lp["budget"], 0) if lp else "—",
                         fmt(lp["tau"]) if lp else "—",
                         fmt(lp["eta"]) if lp else "—",
                         fmt(lp["c"], 2) if lp else "—",
                         (str(lp["converged"]) if lp else "—"),
                         (lp["verdict"] if lp else "not run (screen decided)"),
                         ("%.0f" % lp["lp_s"]) if lp else "—"])
        body.sort(key=lambda x: str(x[0]))
        out.append("## " + title)
        out.append("")
        out.append(md_table(["cell", "lvl", "B", "c(stored dual)", "screen", "τ₀", "η₀",
                             "budget+bonus", "τ(R6)", "η(R6)", "c=dτ/de", "conv", "verdict",
                             "LP s"], body))
        out.append("")

    idr = [r for r in lps if r["use_id"]]
    if idr:
        out.append("## (R6) + Lemma ID's certified weight-1 row")
        out.append("")
        out.append(md_table(["cell", "B1", "B2", "budget", "τ", "η", "c", "conv", "verdict",
                             "LP s"],
                            [[r["nid"], r["B1"], r["B2"], r["budget"], fmt(r["tau"]),
                              fmt(r["eta"]), fmt(r["c"], 2), r["converged"], r["verdict"],
                              "%.0f" % r["lp_s"]] for r in idr]))
        out.append("")

    out.append("## The screen over EVERY open k0_00 cell (166 cells, %.1f s of CPU total)"
               % summ["wall_s"])
    out.append("")
    out.append(md_table(["quantity", "value"], [
        ["open cells with an LP record", summ["n"]],
        ["…of them CONVERGED (τ = budget exactly)", summ["n_converged"]],
        ["PROVED-USELESS for (R6) (c ≥ B on a converged optimum)", summ["proved_useless"]],
        ["…as a share of the converged cells", "%d / %d" % (summ["proved_useless_of_converged"],
                                                            summ["n_converged"])],
        ["screen candidates (c < B; inconclusive, needs the LP)", summ["candidates"]],
        ["mean B / mean c (stored dual)", "%.2f / %.2f" % (summ["mean_B"], summ["mean_c"])],
        ["Lemma ID: cells with c_ID ≥ B_ID (row adds nothing)", "%d / %d" % (summ["cID_ge_BID"],
                                                                            summ["n"])],
        ["Lemma ID: cells where B_ID = 0 (row literally vacuous)", summ["B_ID_zero"]],
        ["mean c_ID against B_ID ≤ 1", "%.2f" % summ["mean_cID"]]]))
    out.append("")

    out.append("## The class row: non-simple corners and whether the teleport licenses it")
    out.append("")
    out.append(md_table(["class", "k", "N", "non-simple corners", "corner-slot extension(s)",
                         "row weight B at s0", "verdict"],
                        [[n, r["k"], r["N"], ", ".join(r["nonsimple"]) or "—",
                          ", ".join("%s→%s %s" % (c["corner"], c["extension"],
                                                  c.get("status_head", "?"))
                                    for c in r["corners"]) or "—",
                          r["B_row_s0"], r["verdict"]] for n, r in cls.items()]))
    out.append("")

    out.append("## A150's band under \"the root corner is the DEEPEST corner\"")
    out.append("")
    out.append(md_table(["quantity", "value"], [
        ["a_w(0.3) (Lemma ID transported to s0 by K0-WIDEN)", "%.5f" % band["a_w_ID"]],
        ["A150 band cells", band["n_band"]],
        ["…that admit a pose with DEPTH ≥ 0.3", band["n_deep_band"]],
        ["raw 6×6×6 cells that do", "%d / 216" % band["n_deep_all"]],
        ["position cells (of 36) carrying a deep tilt bin", len(band["pos_cells_deep"])],
        ["factor on ONE corner of A150's product", "%.3f" % (band["n_deep_band"] /
                                                            float(band["n_band"]))]]))
    out.append("")

    # ---------------- price
    lp_k0 = [r for r in lps if r["cls"] == "k0_00" and r.get("lp_s")]
    lp_t5 = [r for r in lps if r["cls"] == "trump5" and r.get("lp_s")]
    mean_k0 = sum(r["lp_s"] for r in lp_k0) / max(1, len(lp_k0))
    mean_t5 = sum(r["lp_s"] for r in lp_t5) / max(1, len(lp_t5))
    kills = [r for r in lps if r.get("verdict") == "kill-candidate"]
    # ATTRIBUTABLE (A109's convention): the cell was genuinely alive at the LP under the SAME
    # cores (eta0 >= 0) and the row drives eta < 0.  A cell with eta0 < 0 was already LP-dead
    # under its cores and its death is not the row's doing.
    alive0 = [r for r in lps if r.get("eta0") is not None and r["eta0"] >= -1e-9
              and r.get("tau") is not None]
    attributable = [r for r in alive0 if r.get("eta", 0.0) <= -1e-3]
    worse = [r for r in lps if r.get("eta") is not None and r["eta"] > r["eta0"] + 1e-9]
    price = dict(
        n_lp=len(lps), n_lp_k0=len(lp_k0), n_lp_trump5=len(lp_t5),
        mean_lp_s_k0=round(mean_k0, 1), mean_lp_s_trump5=round(mean_t5, 1),
        total_lp_cpu_h=round(sum(r["lp_s"] for r in lps) / 3600.0, 3),
        kill_candidates=len(kills), kill_nids=[r["nid"] for r in kills],
        n_alive_at_eta0=len(alive0), attributable_kills=len(attributable),
        attributable_nids=[r["nid"] for r in attributable],
        n_eta_worse_than_eta0=len(worse),
        mean_eta_minus_eta0=round(sum(r["eta"] - r["eta0"] for r in lps
                                      if r.get("eta") is not None) / max(1, len(lps)), 4),
        mean_c_R6only=round(sum(r["c"] for r in lps if r.get("c") is not None and not r["use_id"])
                            / max(1, len([r for r in lps if not r["use_id"]])), 3),
        mean_B_R6only=round(sum(r["B1"] for r in lps if r.get("c") is not None and not r["use_id"])
                            / max(1, len([r for r in lps if not r["use_id"]])), 3),
        min_c_minus_B_R6only=round(min((r["c"] - r["B1"]) for r in lps
                                       if r.get("c") is not None and not r["use_id"]), 3),
        screen_cpu_s_for_166_cells=summ["wall_s"],
        k0_pass_cost_cpu_h_216_l1=round(N_L1 * mean_k0 / 3600.0, 2),
        k0_pass_cost_cpu_h_166_open=round(166 * mean_k0 / 3600.0, 2),
        k0_gain_cpu_h=[0.0, 0.0],
        k0_net_cpu_h=[-round(N_L1 * mean_k0 / 3600.0, 2), -round(166 * mean_k0 / 3600.0, 2)],
        k0_budget_row_cpu_h=K0_ROW, k0_budget_row_after_a141=list(K0_ROW_AFTER_A141),
        k0_frontier=list(K0_FRONTIER), worth_of_one_certified_l1_kill=list(WORTH_L1),
        trump5_row_weight=2, trump5_licensed="s0 only (k6_23 extension is PARTIAL)",
        protected_tier_cpu_h=list(PROTECTED_TIER),
        protected_tier_classes_with_a_licensed_row=[n for n, r in cls.items()
                                                    if r["B_row_s0"] > 0 and n != "k0_00"],
        a150_band_factor=round(band["n_deep_band"] / float(band["n_band"]), 4))
    json.dump(price, open(os.path.join(L.RES, "price154.json"), "w"), indent=1)
    out.append("## Price")
    out.append("")
    out.append(md_table(["item", "value"], [[k, v] for k, v in price.items()]))
    open(os.path.join(L.BASE, "notes", "tables.md"), "w", encoding="utf-8").write("\n".join(out))
    print("\n".join(out[-14:]))
    print("\nwrote notes/tables.md and results/price154.json")


if __name__ == "__main__":
    main()
