"""A255: results/sense255.md from sense255.jsonl, slide255_summary.json, local255.jsonl, blocked255.jsonl,
ringsense255.jsonl (whatever rows exist: the ring run is detached and resumable)."""
import collections
import json
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.abspath(os.path.join(HERE, '..', 'results'))


def rows(name):
    p = os.path.join(RES, name)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []


def shape(cells):
    k = sorted(c[2:] for c in cells)
    if len(cells) == 1:
        return 'single box' if k == ['00'] else 'single slot'
    if len(cells) == 2 and '00' in k:
        return 'corner domino {c00, slot}'
    if len(cells) == 3 and len({c[:2] for c in cells}) == 1:
        return 'corner triple'
    return '%d cells, %d corners' % (len(cells), len({c[:2] for c in cells}))


def main():
    out = ['# A255 results -- COMMON-SENSE: corpus test, SLIDE-NORMAL corpus test, local search, ring-level search',
           '', 'Generated by `code/summarise255.py`.  Tags: [M] measured, [T-computed] exact finite computation.', '']
    tab = collections.defaultdict(collections.Counter)
    shp = collections.defaultdict(collections.Counter)
    npk = collections.Counter()
    for r in rows('sense255.jsonl'):
        band = r['corpus'] + (' s<4' if r['s'] < 4 - 1e-9 else ' s>=4')
        npk[band] += 1
        for c in r['corners']:
            tab[band][(c['tclass'], c['level'])] += 1
            if c['tclass'] in ('MIXED', 'FLAT+TILT', 'X45') and c['reduce']:
                shp[band][(c['level'], shape(c['reduce'][0]))] += 1
    out += ['## 1. Corpus: toucher senses per corner, and the scope at which Lemma CELLS reduces the corner [M]', '',
            'Class = senses of the wall touchers of the corner\'s two walls that meet c00 or a chain cell (NONE: no toucher;',
            'NOT-DOUBLE: root met by <= 1 square).  Level = smallest scope holding a family with |M| <= |Pi|: L0 = N_c,',
            'L1 = N_c + adjacent boxes, L2 = N_c u N_c\' u N_c\'\', L3 = all border cells, None = family-stuck.', '',
            '| corpus | packings | class | L0 | L1 | L2 | L3 | None |', '|---|---|---|---|---|---|---|---|']
    for band in sorted(tab):
        for cls in sorted({k[0] for k in tab[band]}):
            out.append('| %s | %d | %s | %s |' % (band, npk[band], cls, ' | '.join(
                str(tab[band].get((cls, lv), 0)) for lv in (0, 1, 2, 3, None))))
    out += ['', '**Verdict.** Violations (FLAT+TILT, MIXED, X45) are common in the corpus and EVERY one reduces by CELLS at scope',
            '<= L2; none needs the global family.  The reducing families of the violating corners:', '',
            '| corpus | level | family shape | corners |', '|---|---|---|---|']
    for band in sorted(shp):
        for (lv, sh), v in sorted(shp[band].items(), key=lambda t: (t[0][0], -t[1])):
            out.append('| %s | L%s | %s | %d |' % (band, lv, sh, v))
    sp = os.path.join(RES, 'slide255_summary.json')
    if os.path.exists(sp):
        d = json.load(open(sp))
        out += ['', '## 2. Corpus: SLIDE-NORMAL (the normal cell T of every tilted wall toucher, both directions) [M]', '',
                '| corpus | OUT | FREE | NORMAL | SLIDE (one meeter: teleports) | BLOCKED (>= 2 meeters) |', '|---|---|---|---|---|---|']
        for band, t in d['status'].items():
            out.append('| %s | %d | %d | %d | %d | %d |' % (band, t.get('OUT', 0), t.get('FREE', 0), t.get('NORMAL', 0),
                                                           t.get('SLIDE', 0), t.get('BLOCKED', 0)))
        out += ['', 'Blocker multisets (W = toucher of the same wall, a = another meeter of the cell c, U = neither):', '']
        for band, t in d['blocked_types'].items():
            out.append('* %s: %s' % (band, ', '.join('%s %d' % kv for kv in t.items())))
        out += ['', 'PI claim (c) literal ("a square above s1 can never be a second meeter of c"), c = the farthest cell met by s1: %s'
                % json.dumps(d['pi_claim_c'])]
    for name, title in (('local255.jsonl', '## 3. Local search, counter-hypothesis WITHOUT the slide-block clause [M]'),
                        ('blocked255.jsonl', '## 4. Local search WITH the slide-block clause (five squares) [M]')):
        rr = rows(name)
        if rr:
            out += ['', title, '', '| type | verdict | sup margin | restarts | s |', '|---|---|---|---|---|']
            out += ['| %s | %s | %.4f | %d | %.0f |' % (r['type'], r['verdict'], r['sup_margin'], r['restarts_used'], r['seconds'])
                    for r in rr]
    rr = rows('ringsense255.jsonl')
    if rr:
        out += ['', '## 5. Ring level: the all-ADJ ring with a PRESCRIBED sense pattern (43 orbits) [M]', '',
                'Pattern order B_BL A_BL B_BR A_BR B_TR A_TR B_TL A_TL; sup of A249\'s ring margin with the sense terms.', '',
                '| pattern | minority | side | verdict | sup margin | restarts | s |', '|---|---|---|---|---|---|---|']
        out += ['| %s | %d | %.6f | %s | %.5f | %d | %.0f |' % (r['pattern'], r['n_minority'], r['s'], r['verdict'],
                                                                r['sup_margin'], r['restarts_used'], r['seconds']) for r in rr]
        ex = [r for r in rr if r['verdict'] == 'RING-EXISTS' and r['n_minority'] > 0]
        out += ['', '**Mixed-sense rings found: %d of %d mixed rows done** (%d rows in all; the run is resumable: '
                '`bash attempts/A255-common-sense/code/run255.sh ring`).' %
                (len(ex), sum(1 for r in rr if r['n_minority'] > 0), len(rr))]
    open(os.path.join(RES, 'sense255.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('\n'.join(out[-12:]))


if __name__ == '__main__':
    main()
