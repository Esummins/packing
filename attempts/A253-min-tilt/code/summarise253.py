"""A253 summary: results/mintilt253.md from the rows (curve, bisect, minimax, room, limit, cert).
Re-runnable at any time; the detached ladder calls it after every stage.
    python summarise253.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ATT = os.path.abspath(os.path.join(HERE, '..'))
RES = os.path.join(ATT, 'results')
sys.path.insert(0, HERE)


def rows(fn):
    p = os.path.join(RES, fn)
    return [json.loads(l) for l in open(p, encoding='utf-8') if l.strip()] if os.path.exists(p) else []


def jload(fn):
    p = os.path.join(RES, fn)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else None


def main():
    cur, rm = rows('mintilt253_curve.jsonl'), rows('room253.jsonl')
    bis, mm = rows('mintilt253_bisect.jsonl'), rows('mintilt253_minimax.jsonl')
    one, lim, ex = rows('cert253_oneparam.jsonl'), jload('limit253.json'), jload('cert253_exact.json')
    L = ['# A253 -- the MINIMUM-TILT ring: results', '',
         'Generated by `summarise253.py`.  Tilt tau := min(theta, 90 deg - theta) of a ring member;',
         'the common-tilt slice uses the pinwheel sign pattern sigma = 00110011 (A249\'s ring).', '']

    L += ['## 1. THETA_MIN(s): the joint ring + poker margin M(tau, s)', '',
          'M = sup over the eight deltas and the poker pose of min(ring feasibility without the',
          'tilt block, A252 poke_margin).  M > 0 means: a ring of the family AND a ninth square',
          'whose interior meets the slot-overlap ribbon exist at that common tilt.', '',
          '| s | tau (deg) | M | ring feas | poker wall | binding term |',
          '|---|---|---|---|---|---|']
    for r in sorted(cur, key=lambda q: (q['side'], -q['tau_deg'])):
        b = (r.get('binding') or [['-', 0]])[0]
        L.append('| %s | %.3f | %+.6f | %+.6f | %s | %s %+.5f |'
                 % (r['side'], r['tau_deg'], r['M'], r['feas'], r['wall'], b[0], b[1]))
    L += ['', 'Least tilt at which M > 0 was found, per side (the effort is the row count above',
          'times ~40 s of Nelder-Mead at maxiter 900, warm-started down the ladder):', '']
    for sd in sorted({r['side'] for r in cur}):
        pos = [r['tau_deg'] for r in cur if r['side'] == sd and r['M'] > 0]
        neg = [r['tau_deg'] for r in cur if r['side'] == sd and r['M'] <= 0]
        L.append('- s = %s: M > 0 down to tau = %s deg; not resolved at %s'
                 % (sd, min(pos) if pos else None, sorted(neg)))
    if bis:
        L += ['', '### bisection brackets', '',
              '| s | sigma | kind | lo (deg) | hi (deg) | M at hi |', '|---|---|---|---|---|---|']
        for r in bis:
            L.append('| %s | %s | %s | %.4f | %.4f | %s |'
                     % (r['side'], r['sigma'], r['kind'], r['lo_deg'], r['hi_deg'],
                        None if not r['best'] else round(r['best']['M'], 6)))
    if mm:
        L += ['', '### (ii) non-uniform: minimise the maximum tilt', '',
              '| s | start | max tilt (deg) | margin |', '|---|---|---|---|']
        for r in mm:
            b = r['best']
            L.append('| %s | %s | %s | %s |' % (r['side'], r['start'],
                     None if not b else round(b['maxtilt_deg'], 4),
                     None if not b else round(b['margin'], 6)))

    L += ['', '## 2. ROOM: the capacity of the pocket against the tilt', '',
          'FIT(k) = A222 region search + sup-margin polish (a lower bound); PIERCE(k) = A237\'s',
          'box-valid piercing residual 0 (a certificate, over 1-degree tilt bins).', '',
          '| s | tau (deg) | FIT >= | PIERCE <= | pocket area | 1 more beside the poker? |',
          '|---|---|---|---|---|---|']
    for r in sorted(rm, key=lambda q: (q['side_key'], -q['tau_deg'])):
        L.append('| %s | %.3f | %d | %d | %.4f | %s |'
                 % (r['side_key'], r['tau_deg'], r['capacity_lo'], r['capacity_hi'],
                    r['pocket_area'], r.get('beside_poker', {}).get('one', {}).get('fits')))

    if lim:
        L += ['', '## 3. The FLUSH LIMIT (tau = 0), exactly', '',
              '| s | min pair gap | hole side (s-2) | notch | ribbon inside the wall block | '
              'HOLE-ONE max |(p-q).u| |', '|---|---|---|---|---|---|']
        for k, v in sorted(lim.items()):
            L.append('| %s | %+.0e | %.4f | %.4f x 1 | %s | %.5f (<= 0.5) |'
                     % (k, v['min_gap'], v['hole_side'], v['notch_dims'][0][0],
                        all(v['ribbon_in_block'].values()), v['hole_one_measured']))
        L += ['', 'The limit pocket is the central square hole of side s - 2 plus four isolated',
              '1 x (s - 3) notches; capacity EXACTLY 1 by Lemma HOLE-ONE and Lemma NOTCH-NARROW.']

    if ex:
        L += ['', '## 4. Exact (rational) re-verification of the reported rings and pokers', '',
              '| s | tau (deg) | ring ok | exact min gap | poker ok | poker min gap | ribbon gap |',
              '|---|---|---|---|---|---|---|']
        for e in ex:
            L.append('| %s | %.3f | %s | %+.2e | %s | %+.2e | %+.2e |'
                     % (e['side'], e['tau_deg'], e['ring_ok'], e['exact_min_gap'],
                        e.get('poker_ok'), e.get('poker_min_gap', 0), e.get('poker_ribbon_gap', 0)))

    if one:
        L += ['', '## 5. The one-parameter box certificate (fixed tilt, s varying)', '',
              '| box | tau (deg) | [s0, s1] | ddelta | PIERCE(1) residual | PIERCE(2) residual | ok |',
              '|---|---|---|---|---|---|---|']
        for r in one:
            c = r.get('cert', {})
            L.append('| %d | %.3f | [%.4f, %.4f] | %s | %s | %s | %s |'
                     % (r['box'], r['tau_deg'], r['s0'], r['s1'],
                        None if 'ddelta_max' not in r else round(r['ddelta_max'], 5),
                        c.get('pierce1', {}).get('residual'), c.get('pierce2', {}).get('residual'),
                        r.get('ok')))
    open(os.path.join(RES, 'mintilt253.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote results/mintilt253.md (%d curve, %d room, %d limit rows)'
          % (len(cur), len(rm), 0 if not lim else len(lim)), flush=True)


if __name__ == '__main__':
    main()
