"""
A57 rung-3 shadow tree: ONE-LEVEL sub-stratification of a shadow stratum (k5_11 / k5_16),
interior-first, breadth-first, easiest-first, resumable, checkpointed.

Branch (A54 substrat semantics, unchanged):
  parent = the k pinned slot squares, budget 11-k.
  zone Z (rectangle of centres) x [0,90] is covered by closed boxes {B_i}; children are
     NO   : parent + NO-family (Z x [0,90])                 budget 11-k      (stays at budget)
     YES_i: parent + core box B_i                           budget 11-k-1
  "no square centre in Z" OR "some square has (centre,theta) in some B_i" is exhaustive
  (the cover is closed and vacuous boxes contain no admissible placement), so the parent
  stratum is EMPTY as soon as every child carries an exact certificate.
  The sole arbiter of a kill is verify_case.py on the exact rational certificate (A54 S0):
  tau < budget is NOT a kill and tau >= budget is NOT a survival.

A57 additions over A54's substrat.py:
  * theta subdivision uniform in t = tan(theta/2), so the core half-side
    a = (1/2 - hd)/(1 + (t1-t0)) is UNIFORM over the cover (A24 (iii) wants a >= 0.31..0.35;
    A54's degree-uniform cover gave a = 0.022..0.043 in the interior/side zones).
  * easiest-first ordering: children farthest from Trump's ghost placements first
    (A54 S1: the stragglers' LP optima are Trump's ghost re-decorated, so the hard children
    are the ones sitting on his squares).
  * sibling COLUMN folding (A55/k3_ext E3): atoms generated by solved siblings are folded
    into the warm start of the next child.  Columns only -- rows are never folded (memory)
    and rows are never pruned inside a child solve.
  * fully resumable: one jsonl record per finished child, one node json per child, a
    progress json rewritten after every child.  Re-running the same shard skips finished
    children and re-folds their atoms.

Canary: trump5 is never a target; every child is checked with substrat.trump_realizes and,
if Trump's packing realises it, it is recorded and NEVER certified.
"""
