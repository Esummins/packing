# ------------------------------------------------------------------ cover
def theta_edges(nth):
    """theta boundaries uniform in t = tan(theta/2) over [0,1] -> [0,90] degrees."""
    return [math.degrees(2.0 * math.atan(k / nth)) for k in range(nth + 1)]


def cover(rect, s, w, nth, a_min, max_split=3):
    """closed cover of rect x [0,90] by boxes of centre-width ~w and t-uniform theta cells.
    Vacuous boxes are dropped (sound: they contain no admissible placement).  Boxes whose
    rational core is empty or smaller than a_min are bisected up to max_split times."""
    x0, x1, y0, y1 = rect
    nx = max(1, int(math.ceil((x1 - x0) / w)))
    ny = max(1, int(math.ceil((y1 - y0) / w)))
    te = theta_edges(nth)
    todo = [Box(x0 + (x1 - x0) * i / nx, x0 + (x1 - x0) * (i + 1) / nx,
                y0 + (y1 - y0) * j / ny, y0 + (y1 - y0) * (j + 1) / ny,
                te[k], te[k + 1])
            for i in range(nx) for j in range(ny) for k in range(nth)]
    out, bad = [], []
    for _ in range(max_split + 1):
        nxt = []
        for b in todo:
            if b.vacuous(s):
                continue
            c = b.core()
            if c is not None and float(c.a) >= a_min:
                out.append(b)
            else:
                nxt.append(b)
        if not nxt:
            break
        todo = [h for b in nxt for h in b.split()]
    else:
        for b in todo:
            if b.vacuous(s):
                continue
            if b.core() is not None:
                out.append(b)       # keep: sound, just weaker than a_min
            else:
                bad.append(b)       # NOT sound to keep: no rational core
    return out, bad, (nx, ny, nth)


# ------------------------------------------------------------------ ordering
def ghost_placements():
    p = os.path.abspath(os.path.join(BASE, "..", "A03-upper-reconstruct", "trump11_float.json"))
    X = json.load(open(p))["X"]
    return [(x, y, math.tan((math.degrees(th) % 90.0) * math.pi / 360.0)) for (x, y, th) in X]


def ghost_dist(b, G):
    """distance from a box's midpoint to the nearest Trump placement in (x, y, 2t)."""
    cx, cy = 0.5 * (b.x0 + b.x1), 0.5 * (b.y0 + b.y1)
    t = 0.5 * (math.tan(math.radians(b.th0) / 2) + math.tan(math.radians(b.th1) / 2))
    return min(math.sqrt((cx - x) ** 2 + (cy - y) ** 2 + (2 * (t - tt)) ** 2) for (x, y, tt) in G)


# ------------------------------------------------------------------ children
def build_children(name, zone, w, nth, cw, a_min, pin_delta=0.0, side=None):
    """pin_delta > 0 emits SLACK pin cores (A63 route (b) / T21): a square pin box of half-width
    delta/sqrt(2) gives core half-side a = 1/2 - delta and hence rho = delta, so one fixed-side
    certificate transfers to a slab of relative width delta/(5/2) instead of ~4e-10.  It also
    weakens the pin hypothesis (the pinned square need only lie within delta/sqrt(2) of the slot),
    which ENLARGES the stratum -- sound, and a strictly stronger kill.  Gate re-checked (T23):
    min slot separation is 1.0, 2h = 1.41e-2 and 2a = 0.98 are both below it, so the h-balls and
    the fattened cores stay pairwise disjoint and no centre can lie in two pin boxes."""
    SF = S0F if side is None else float(_F(side))
    slots = [tuple(p) for p in json.load(open(os.path.join(A53, "results", "name_to_slots.json")))[name]]
    if side is not None and abs(SF - S0F) > 1e-12:
        slots = slots_at(slots, _F(side))
    hh = 0.0 if pin_delta <= 0 else pin_delta / math.sqrt(2.0)
    pins = [Box(x - hh, x + hh, y - hh, y + hh, 0.0, 0.0) for (x, y) in slots]
    rect = zones(SF, cw)[zone]
    boxes, bad, grid = cover(rect, SF, w, nth, a_min)
    G = ghost_placements()
    kids = [dict(id=f"{name}_{zone}_NO", kind="NO", box=None, score=1e9,
                 hyp=Hyp(pins, [NoFam(rect[0], rect[1], rect[2], rect[3], [(0.0, 90.0)])]),
                 budget=11 - len(slots), a=None)]
    scored = sorted(boxes, key=lambda b: -ghost_dist(b, G))     # easiest (farthest) first
    for i, b in enumerate(scored):
        st, info = classify(b, pins, slots)
        bid = f"{name}_{zone}_Y{i:04d}"
        # T5'' (A96): trim tilt sub-intervals that are dead by logic before the node is ever
        # solved.  node = trimmed child(ren) + excluded intervals.  A trimmed child is a SUB-BOX,
        # so its certificate is the ordinary one; each excluded interval is a T5-with-range
        # instance (trim57.split_bin returns the witness pin for each).  Suffixed ids (…a, …b)
        # appear only when a bin survives in more than one piece; plain ids are unchanged, so
        # nothing already recorded is renamed.
        subs, excl = ([b], []) if (st != "ok" or not trim57.TRIM) else trim57.trim_box(b, slots)
        if st == "ok" and not subs:
            kids.append(dict(id=bid, kind="YES", box=b, score=ghost_dist(b, G),
                             a=float(b.core().a), pin="contradictory", pin_info="trim",
                             trim_excluded=excl, hyp=Hyp(pins + [b], []),
                             budget=11 - len(slots) - 1))
            continue
        for k, sb in enumerate(subs):
            kid_id = bid if len(subs) == 1 else f"{bid}{chr(97 + k)}"
            kids.append(dict(id=kid_id, kind="YES", box=sb, score=ghost_dist(sb, G),
                             a=float(sb.core().a), pin=st, pin_info=info,
                             trim_excluded=(excl if k == 0 else []),
                             trim_from=(None if (len(subs) == 1 and not excl) else
                                        dict(th0=b.th0, th1=b.th1)),
                             hyp=Hyp(pins + [sb], []), budget=11 - len(slots) - 1))
    return kids, bad, slots, rect, grid


# ------------------------------------------------------------------ eps_geo retry (T14)
def eps_geo_margins(tau, budget):
    """Which row-shrink margins are worth trying, from the scale headroom.

    eps_geo only RAISES tau (shrunk rows are strictly harder), and certification needs
    tau*1.005 < budget.  Measured rises: +1.59 % at margin 0.002 (k5_11_interior_Y0107,
    4.500000 -> 4.571429) and +0.72 % at margin 0.0005 on the k5_11 parent.  So a child sitting
    AT the budget (the T11 knife edge, scale ceiling 1.0000) can never be helped by a margin --
    and trying anyway cost 1847 s at k5_11_interior_Y0036 before falling through to depth 2,
    which is where it belonged from the start.  Gate on the ceiling."""
    ceil = budget / tau if tau > 0 else 0.0
    if ceil < 1.010:
        return ()                       # no headroom: straight to depth 2
    if ceil < 1.050:
        return (0.0005, 0.001)          # thin: small margins only
    return (0.002, 0.004)


def run_eps_geo(node_path, kid, a, certdir, log, margins=None):
    """A certificate with tau comfortably under budget can still FAIL with **0 holes** and a
    handful of witness boxes the verifier cannot DECIDE -- atoms sitting on placement boundaries,
    a degeneracy that more depth does not fix (measured at k5_11_interior_Y0107: the same 8
    undecided boxes at depth 56, 64 and 72).  A56's row-shrink margin is the cure: re-solve the
    node LP with EPS_GEO = margin so the measure is robust to boundary effects, then certify.
    Sound: shrinking rows makes the LP HARDER (tau rises), and the arbiter is unchanged."""
    if margins is None:
        res0 = json.load(open(node_path))
        margins = eps_geo_margins(res0["tau"], kid["budget"])
    out = dict(eps_geo=[])
    if not margins:
        out["cert"] = ("ALIVE-at-LP (no scale headroom for a row-shrink margin) "
                       "-> queued for depth 2 (deepen.py)")
        log(f"    eps_geo skipped: scale ceiling too tight for a margin")
        return out
    for m in margins:
        cert_out = os.path.join(certdir, f"{kid['id']}_epsgeo{m:g}.json")
        cmd = [sys.executable, os.path.join(HERE, "certify.py"), node_path,
               "--s_rat", str(_F(getattr(a, "side", S_RAT))),
               "--eps_geo", f"{m:g}", "--rounds", "1", "--jobs", str(min(a.jobs, VERIFY_JOBS_CAP)),
               "--depth", str(a.depth), "--time_limit", str(a.cert_time),
               "--resolve_time", str(a.cert_time), "--out", cert_out, "--scale", "0",
               "--scale_cap", f"{a.scale_cap:.5f}", "--max_w", "32", "--loop_cols"]
        t0 = time.time()
        p = subprocess.run(cmd, capture_output=True, text=True)
        log(p.stdout[-2500:])
        step = dict(eps_geo=m, rc=p.returncode, seconds=round(time.time() - t0, 1))
        out["eps_geo"].append(step)
        if p.returncode == 0:
            open(cert_out + ".PASS", "w").write("ok")
            out.update(cert="PASS", cert_path=cert_out, eps_geo_used=m)
            return out
    out["cert"] = "FAIL(eps_geo retries exhausted) -> queued for depth 2 (deepen.py)"
    return out


# ------------------------------------------------------------------ EPS_CORE ladder (T11)
def run_eps_ladder(node_path, kid, a, certdir, log, eps=(5e-4, 2e-4, 5e-5)):
    """A child that converges to tau >= budget is normally being held there by caselp's 2e-3
    core shell, which `verify_case.py` (exact exemption) does not require.  Re-solve at smaller
    EPS_CORE -- strictly fewer rows, so tau can only fall -- and certify.  Sound in the only way
    that matters: the arbiter is unchanged, so a shell that WAS needed just makes the exact
    verification FAIL."""
    res0 = json.load(open(node_path))
    warm2 = dict(atoms=[(x[0], x[1]) for x in res0.get("atoms_all", [])], rows=[])
    out = dict(eps_ladder=[])
    try:
        for e in eps:
            caselp.EPS_CORE = e
            t0 = time.time()
            r = solve_node(float(_F(getattr(a, "side", S_RAT))), kid["hyp"], kid["budget"],
                           sym_kind="C1", warm=warm2,
                           time_limit=a.time_limit, max_iter=900, out=None, log=log,
                           prune=0, prune_cols=3, col_stop_iter=10 ** 6, col_stop_cov=1.002,
                           max_cols_add=400, max_rows_add=2000, fine_slack=0.05, alternate=True)
            r["eps_core"] = e
            step = dict(eps_core=e, tau=r["tau"], eta=r["tau"] - kid["budget"],
                        conv=r["converged"], lp_s=round(time.time() - t0, 1))
            if r["tau"] < kid["budget"]:
                np2 = node_path.replace(".json", f"_eps{e:g}.json")
                json.dump(r, open(np2, "w"))
                cert_out = os.path.join(certdir, f"{kid['id']}_eps{e:g}.json")
                cmd = [sys.executable, os.path.join(HERE, "certify.py"), np2,
                       "--s_rat", str(_F(getattr(a, "side", S_RAT))),
                       "--rounds", str(a.rounds), "--jobs", str(min(a.jobs, VERIFY_JOBS_CAP)), "--depth", str(a.depth),
                       "--time_limit", str(a.cert_time), "--out", cert_out, "--scale", "0",
                       "--scale_cap", f"{a.scale_cap:.5f}", "--max_w", "64", "--loop_cols"]
                p = subprocess.run(cmd, capture_output=True, text=True)
                log(p.stdout[-2000:])
                step["cert"] = "PASS" if p.returncode == 0 else f"FAIL(rc={p.returncode})"
                out["eps_ladder"].append(step)
                if p.returncode == 0:
                    open(cert_out + ".PASS", "w").write("ok")
                    out.update(cert="PASS", cert_path=cert_out, eps_core_used=e,
                               tau_ladder=r["tau"], eta_ladder=r["tau"] - kid["budget"])
                    return out
            else:
                out["eps_ladder"].append(step)
    finally:
        caselp.EPS_CORE = 2e-3          # never leak the shrunken shell to the next child
    out["cert"] = ("ALIVE-at-LP after EPS_CORE ladder"
                   if all(s.get("cert") is None for s in out["eps_ladder"])
                   else "FAIL(eps ladder exhausted)")
    return out


def defer(kid_id, exc, log, base, key, stats):
    """T19 (A60's tree60.defer, adopted): a transient COMMIT spike must not destroy a queue.

    The machine's binding constraint is the commit limit, and a spike elsewhere can make a
    ~40 MiB allocation fail here.  Previously that killed the worker outright and the whole
    remaining shard queue died with it (measured: one tree shard and one deepen job lost
    together).  On MemoryError we now record the node, sleep, and carry on -- and crucially we
    do NOT append a summary record, so the node stays absent from `done` and is retried on the
    next pass.  Deferring is always safe: it can only postpone work, never assert a verdict.
    """
    import json as _json, time as _time, gc as _gc
    _gc.collect()
    p = os.path.join(base, "results", f"deferred_{key}.jsonl")
    try:
        with open(p, "a") as f:
            f.write(_json.dumps(dict(id=kid_id, error=repr(exc)[:200],
                                     when=_time.strftime("%Y-%m-%d %H:%M:%S"))) + chr(10))
    except Exception:
        pass
    stats["deferred"] = stats.get("deferred", 0) + 1
    log(f"    DEFERRED {kid_id}: {repr(exc)[:120]} -- sleeping 30 s, node left NOT done")
    _time.sleep(30)


