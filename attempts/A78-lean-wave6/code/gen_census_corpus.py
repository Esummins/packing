#!/usr/bin/env python3
"""Regenerate lean/PackingCertMathlib/PackingCertMathlib/CensusCorpus.lean from A72's census JSON
(slot code = corner*9 + cellx*3 + celly; corner order BL, BR, TR, TL)."""
import json, os, sys
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
d = json.load(open(os.path.join(REPO, 'attempts/A72-census-cleanroom/results/census_cleanroom.json')))
def dec(s):
    parts = s.split('|'); assert len(parts) == 4
    codes = []
    for c, p in enumerate(parts):
        for k in range(0, len(p), 2):
            codes.append(c * 9 + int(p[k]) * 3 + int(p[k + 1]))
    return sorted(codes)
tuples = [dec(t) for t in d['tuples']]
classes = [[dec(m) for m in mem] for r, mem in sorted(d['classes'].items())]
trump = [dec(t) for t in d['trump']['matched_tuples']]
assert len(tuples) == 1110 and len(classes) == 163 and sum(len(c) for c in classes) == 1110 and len(trump) == 1
out = ["import PackingCertMathlib.Census\n",
       "/-!\nAuto-generated by attempts/A78-lean-wave6/code/gen_census_corpus.py from\n`attempts/A72-census-cleanroom/results/census_cleanroom.json` (A72 clean-room census, sha256 tuple_set\n%s).\nEach tuple is the sorted list of slot codes `corner*9 + cellx*3 + celly` (corner 0 = BL, 1 = BR, 2 = TR,\n3 = TL, as in `Skeleton.lean`); `corpusClasses` lists A72's 163 D4 orbits.  Do not edit by hand.\n-/\n" % d['sha256']['tuple_set'],
       "namespace PackingCert.S11.CensusCorpus\n",
       "/-- A72's 1110 Young slot-sets (as slot-code lists). -/",
       "def corpusTuples : List (List Nat) := [",
       ",\n".join("  " + json.dumps(t) for t in tuples), "]\n",
       "/-- A72's 163 D4 orbits (each a list of slot-code lists). -/",
       "def corpusClasses : List (List (List Nat)) := [",
       ",\n".join("  " + json.dumps(c) for c in classes), "]\n",
       "/-- Trump's skeleton ((2,1),(1),(1),∅) as found by A72's canary. -/",
       "def corpusTrump : List Nat := %s\n" % json.dumps(trump[0]),
       "end PackingCert.S11.CensusCorpus"]
p = os.path.join(REPO, 'lean/PackingCertMathlib/PackingCertMathlib/CensusCorpus.lean')
open(p, 'w', encoding='utf-8', newline='\n').write("\n".join(out) + "\n")
print('wrote', p)
