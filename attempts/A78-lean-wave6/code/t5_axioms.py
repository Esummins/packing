#!/usr/bin/env python3
"""A78 T5: emit lean/PackingCertMathlib/scratch/AxiomsCorpus.lean.

Prints the axioms of every replayed certificate's `check_*` fact and its composed
kill / no-family theorem, plus the corpus theorems of the corpora that are complete.
Run it with
    python attempts/A78-lean-wave6/code/lakeb.py --env scratch/AxiomsCorpus.lean
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
A78 = REPO / "attempts" / "A78-lean-wave6"
OUT = REPO / "lean" / "PackingCertMathlib" / "scratch" / "AxiomsCorpus.lean"
ORDER = A78 / "results" / "t5_order.json"
TIM = A78 / "results" / "t5_timings.jsonl"
TRAP = ["k6_07", "k6_19", "k6_21", "k6_22", "k6_23", "k6_24"]


def main():
    order = {r["name"]: r for r in json.loads(ORDER.read_text(encoding="utf-8"))}
    ok = []
    for line in TIM.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            if r.get("status") == "OK" and r["name"] not in [x["name"] for x in ok]:
                ok.append(r)
    okset = {r["name"] for r in ok}
    ok.sort(key=lambda r: (r["corpus"], r["name"]))

    complete = {}
    for c in ("K61", "P1", "THMU"):
        mem = [n for n, r in order.items() if r["corpus"] == c]
        complete[c] = all(n in okset for n in mem)
    complete["TRAP"] = all(n in okset for n in TRAP)

    L = ["-- A78 T5 axiom audit (auto-generated by attempts/A78-lean-wave6/code/t5_axioms.py).",
         "-- Run: python attempts/A78-lean-wave6/code/lakeb.py --env scratch/AxiomsCorpus.lean",
         ""]
    for r in ok:
        L.append("import PackingCertMathlib.Corpus.%s.Check_%s" % (r["corpus"], r["name"]))
    for c in ("K61", "TRAP", "P1", "THMU"):
        if complete[c]:
            L.append("import PackingCertMathlib.Corpus.%s" % c)
    L.append("")
    for r in ok:
        nm, nf = r["name"], r["nofams"]
        L.append("#print axioms PackingCert.S11.check_%s" % nm)
        L.append("#print axioms PackingCert.S11.%s_%s" % (nm, "no_family" if nf else "kill"))
    L.append("")
    for c in ("K61", "TRAP", "P1", "THMU"):
        if complete[c]:
            L.append("#print axioms PackingCert.S11.corpus_%s" % c)
        else:
            L.append("-- corpus_%s: NOT complete (some certificates PENDING) -- not imported" % c)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote %s: %d certificates, complete corpora %s"
          % (OUT, len(ok), [c for c in complete if complete[c]]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
