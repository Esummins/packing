"""A244: collect every run into results/twelve244.jsonl (the verified candidates), a summary
dict results/summary244.json for the pages, and the report results/twelve244.md."""
import glob
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ATT = os.path.abspath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import cells244 as C          # noqa: E402

RES = os.path.join(ATT, 'results')
SHAT = 3.877084
KEEP = ('rid', 'mode', 'delta', 's', 'z', 'meeters', 'supply', 'tilts_deg', 'seed_family',
        'min_wall_gap', 'min_pair_gap', 'worst_second_depth', 'fj_free_res', 'fj_loaded',
        'meeters_all_loaded', 'locked', 'unloadable_meeters', 'n_meeters', 'side', 'family')


def load(pat):
    out = []
    for p in sorted(glob.glob(os.path.join(RES, pat))):
        for line in open(p, encoding='utf-8'):
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def verified(recs):
    out = []
    for r in recs:
        c = r.get('cert')
        if not c or not c.get('PASS'):
            continue
        d = {k: r[k] for k in KEEP if k in r}
        d['s_cert'] = c['s_cert']
        d['cert'] = c
        d['mode'] = r.get('mode', 'twelve')
        out.append(d)
    out.sort(key=lambda d: d['s_cert'])
    return out


def curve(recs, mode):
    """best certified side after k runs, in file order."""
    best, out = float('inf'), []
    k = 0
    for r in recs:
        if r.get('mode') != mode:
            continue
        k += 1
        c = r.get('cert')
        if c and c.get('PASS') and c['s_cert'] < best:
            best = c['s_cert']
        out.append((k, best if best < float('inf') else None))
    return out


def probe_table(recs):
    t = {}
    for r in recs:
        key = (r['mode'], r['side'], r.get('delta', 0.0), r.get('tilt_floor_deg', 0.0))
        e = t.setdefault(key, {'n': 0, 'best': float('inf'), 'strict': 0, 'secs': 0.0,
                               'best_cert': None})
        e['n'] += 1
        e['secs'] += r.get('secs', 0.0)
        e['best'] = min(e['best'], r['residual'])
        if r.get('strict_ok'):
            e['strict'] += 1
            c = r.get('cert')
            if c and c.get('PASS') and (e['best_cert'] is None or c['s_cert'] < e['best_cert']):
                e['best_cert'] = c['s_cert']
    return t


def main():
    runs = load('twelve244_*.jsonl')
    probes = load('probe244_*.jsonl')
    vr = verified(runs) + verified(probes)
    vr.sort(key=lambda d: (d['mode'], d['s_cert']))
    with open(os.path.join(RES, 'twelve244.jsonl'), 'w', encoding='utf-8') as f:
        for d in vr:
            f.write(json.dumps(d) + '\n')
    tw = [d for d in vr if d['mode'] == 'twelve']
    fo = [d for d in vr if d['mode'] == 'four']
    hand = {}
    hp = os.path.join(RES, 'hand244.json')
    if os.path.exists(hp):
        hand = json.load(open(hp, encoding='utf-8'))
    pt = probe_table(probes)
    secs = sum(r.get('secs', 0.0) for r in runs) + sum(r.get('secs', 0.0) for r in probes)
    summary = {
        'n_runs': len(runs), 'n_probes': len(probes), 'cpu_hours': secs / 3600.0,
        'n_verified_twelve': len(tw), 'n_verified_four': len(fo),
        'best_twelve': tw[0] if tw else None, 'best_four': fo[0] if fo else None,
        'curve_twelve': curve(runs, 'twelve'), 'curve_four': curve(runs, 'four'),
        'probe': {'%s|%.6f|%g|%g' % k: v for k, v in sorted(pt.items())},
        'hand': hand, 'shat': SHAT,
    }
    with open(os.path.join(RES, 'summary244.json'), 'w', encoding='utf-8') as f:
        json.dump(summary, f, indent=1)
    _md(summary, tw, fo, pt)
    print('runs %d, probes %d, verified 12-stuck %d, verified 4-stuck %d, %.2f CPU-h'
          % (len(runs), len(probes), len(tw), len(fo), secs / 3600.0), flush=True)
    if tw:
        print('best certified 12-STUCK side %.6f (%s)' % (tw[0]['s_cert'], tw[0]['rid']), flush=True)
    if fo:
        print('best certified  4-STUCK side %.6f (%s)' % (fo[0]['s_cert'], fo[0]['rid']), flush=True)


def _md(su, tw, fo, pt):
    L = []
    L.append('# A244 -- the 12-STUCK threshold: measurements\n')
    L.append('Generated by `code/summarise244.py`.  A packing is **12-STUCK** when each of the '
             'twelve border cells (the four corner boxes and the eight wall slots of A243 Lemma '
             'WALL-SLOT) has its interior met by at least two distinct squares.  Every side '
             'quoted as CERTIFIED is `verify244`\'s interval-arithmetic verdict after the '
             'inflation (containment, pairwise interior-disjointness, and >= 2 strictly positive '
             'overlap depths for each of the twelve cells).\n')
    L.append('## 1. The thresholds\n')
    L.append('| condition | least CERTIFIED side | vs 4 | vs s-hat = 3.877084 | witnesses |')
    L.append('|---|---|---|---|---|')
    for lbl, v in (('12-STUCK (all twelve cells)', tw), ('4-STUCK (corner boxes only, control)', fo)):
        if v:
            s = v[0]['s_cert']
            L.append('| %s | **%.6f** | %+.6f | %+.6f | %d |'
                     % (lbl, s, s - 4.0, s - SHAT, len(v)))
        else:
            L.append('| %s | none found | | | 0 |' % lbl)
    L.append('')
    L.append('Effort: %d descent runs + %d fixed-side probe restarts, %.2f CPU-h.  This is '
             'EVIDENCE, not a proof: a side at which the search found nothing is a side at which '
             'the search found nothing.\n' % (su['n_runs'], su['n_probes'], su['cpu_hours']))
    if tw:
        b = tw[0]
        L.append('## 2. The best 12-stuck packing\n')
        L.append('`%s` (seed family %s, crowd margin delta = %g), certified side **%.9f** '
                 '(raw %.9f, inflation lam = %s).\n'
                 % (b['rid'], b.get('seed_family', b.get('family', '?')), b.get('delta', 0),
                    b['s_cert'], b.get('s', b.get('side', float('nan'))), b['cert']['lam']))
        L.append('| cell | meeters | supply of the 2nd meeter |')
        L.append('|---|---|---|')
        for c in C.CELLS:
            sup = b.get('supply', {}).get(c)
            L.append('| %s | %s | %s |' % (c, b['meeters'][c], '' if sup is None else ', '.join(sup)))
        L.append('')
        L.append('Tilts (deg): %s\n' % ', '.join('%.2f' % t for t in b.get('tilts_deg', [])))
        L.append('Fritz-John (free rows only, no crowd rows): residual %s, %s meeters, all '
                 'loaded: %s, LOCKED: %s.\n'
                 % (b.get('fj_free_res'), b.get('n_meeters'), b.get('meeters_all_loaded'),
                    b.get('locked')))
    L.append('## 3. The fixed-side probes (best residual over the restarts)\n')
    L.append('The residual is `max(-min wall gap, -min pair gap, delta - min 2nd depth, 0)`; '
             '0 means a delta-margin stuck packing was found at that exact side.\n')
    L.append('| mode | side | delta | tilt floor | restarts | best residual | strict packings | '
             'least certified |')
    L.append('|---|---|---|---|---|---|---|---|')
    for k in sorted(pt):
        e = pt[k]
        L.append('| %s | %.6f | %g | %g | %d | %.3e | %d | %s |'
                 % (k[0], k[1], k[2], k[3], e['n'], e['best'], e['strict'],
                    '' if e['best_cert'] is None else '%.6f' % e['best_cert']))
    L.append('')
    h = su.get('hand') or {}
    if h:
        L.append('## 4. Structure (code/hand244.py)\n')
        for s, v in sorted((h.get('max_cells') or {}).items()):
            L.append('- side %s: one unit square meets at most **%d** of the twelve cells '
                     '(witness %s, cells %s).' % (s, v['max'], [round(x, 3) for x in v['witness']],
                                                  v['cells']))
        for key in sorted(k for k in h if k.startswith('corner_')):
            e = h[key]
            L.append('- margin %s: ONE square meeting all three cells of a corner: penalty %.3e '
                     '(0 = it exists); TWO disjoint squares each meeting all three (a '
                     'SELF-SUFFICIENT corner): best penalty %.3e over %s restarts.'
                     % (key.split('_')[1], e['one_square']['penalty'],
                        e['two_squares']['penalty'], e['two_squares']['tries']))
        L.append('- %s' % (h.get('reach') or {}).get('note', ''))
        L.append('')
    with open(os.path.join(RES, 'twelve244.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
