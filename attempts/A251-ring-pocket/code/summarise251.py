"""A251 summary -> results/pocket251.md (+ pocket251_summary.json): the analytic constants, the
box-valid certificate's price, and the joint ring + k free squares ladder.

    python summarise251.py
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ATT = os.path.abspath(os.path.join(HERE, '..'))
RES = os.path.join(ATT, 'results')
sys.path.insert(0, HERE)


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else {}


def main():
    cert, joint, ana = load('cert251.json'), load('joint251.json'), load('analytic251.json')
    L = ['# A251 -- RING-POCKET(11): the pocket of the all-ADJ type-T ring family', '',
         'Generated by `summarise251.py`.  Sources: `cert251.json` (the box-valid PIERCE certificate and',
         'its price), `joint251.json` (ring + k free squares as one SAT search), `analytic251.json`',
         '(INRADIUS / THREE-DISC / GAP / MID-NOTCH).', '']
    L += ['## 1. The analytic constants (task 3)', '']
    if ana:
        L += ['| quantity | value |', '| --- | --- |',
              '| `min g`, `g(t) = (1+sin t)/cos t - 2 sin t` | %.5f at %.3f deg |' % (ana['g_min'], ana['g_argmin_deg']),
              '| MID-NOTCH dead for s > | %.5f |' % ana['mid_notch_side_bound'],
              '| robust form `min g2` | %.5f at %.3f deg |' % (ana.get('g2_min', float("nan")), ana.get('g2_argmin_deg', float("nan"))),
              '| robust MID-NOTCH dead for s > | %.5f (window starts at 3.82) |' % ana.get('mid_notch_side_bound_robust', float('nan')),
              '| THREE-DISC radius `1/sqrt3` | %.5f |' % ana['three_disc_radius'],
              '| family samples checked | %d (GAP violations %d, MID-NOTCH violations %d) |'
              % (ana['samples'], ana['gap_violations'], ana['notch_violations']),
              '| max middle-notch inradius over the samples | %.4f (bound 1/2) |' % ana['max_notch_inradius'], '']
    L += ['## 2. The box-valid PIERCE certificate and its price (task 2)', '']
    if cert.get('rings'):
        L += ['| side | ring margin | PIERCE(1) | PIERCE(2) | eps* (PIERCE(2)) | box half-width | boxes (17 coords, /8) |',
              '| --- | --- | --- | --- | --- | --- | --- |']
        for k, v in sorted(cert['rings'].items()):
            for r in v['records']:
                L.append('| %s | %+.5f | %.2e | %.2e | %.4f | %.4f | %.3g |'
                         % (k, r['margin'], r['pierce1_centre'], r['pierce2_best'],
                            r['eps_star_pierce2'], r['radius_pierce2'], r['boxes_pierce2']))
        L.append('')
    for r, p in sorted(cert.get('pilot', {}).items()):
        L += ['* pilot at radius %s: %d boxes, %d certified, %d failed, %d discarded by `margin_ub`, '
              '%d with an empty core; %.3f s per live box, wall %.0f s.'
              % (r, p['boxes'], p['n_certified'], p['n_failed'], p['n_discarded'], p['n_empty_core'],
                 p['seconds_per_live_box'] or 0.0, p['wall_seconds'])]
    if cert.get('pilot'):
        best = sorted(cert['pilot'].items())[0][1]
        eps = cert.get('eps_star_used')
        L += ['', '**Price.** At the admissible half-width the certificate needs the box count above at '
              '%.3f s each: the product law in its counting form (17 coordinates), far beyond the 200 CPU-h stop.'
              % (best['seconds_per_live_box'] or 0.0)]
        if eps:
            L += ['(eps* used: %.4f.)' % eps]
    L += ['', '## 3. Ring + k free squares, the direct obligation (task 4)', '']
    if joint:
        L += ['| side | feasible rings | k = 1 | k = 2 | k = 3 | max &#124;q - O&#124; |', '| --- | --- | --- | --- | --- | --- |']
        for k in sorted(joint):
            v = joint[k]
            row = ['| %s | %s' % (k, v.get('rings', {}).get('n', '-'))]
            for kk in (1, 2, 3):
                r = v.get('fit%d' % kk)
                row.append('%+.5f' % r['sup_margin'] if r else '-')
            f = v.get('far')
            row.append('%.4f' % f['max_dist'] if f else '-')
            L.append(' | '.join(row) + ' |')
        L.append('')
        L += ['`k = 3` with sup margin < 0 at every side is RING-POCKET(11) [T-computed] on the sampled family;',
              'max |q - O| < 1/sqrt3 = 0.57735 is Lemma CENTRE-DISC, which gives capacity <= 2 by THREE-DISC.', '']
    out = {'cert': bool(cert), 'joint': bool(joint), 'analytic': bool(ana)}
    if ana:
        out.update({k: ana[k] for k in ('g_min', 'g_argmin_deg', 'mid_notch_side_bound',
                                        'three_disc_radius') if k in ana})
    if cert.get('rings'):
        recs = [r for v in cert['rings'].values() for r in v['records']]
        out['eps_star_min'] = min(r['eps_star_pierce2'] for r in recs)
        out['boxes_max'] = max(r['boxes_pierce2'] for r in recs)
        out['all_capacity_le_2'] = all(r['capacity_le_2'] for r in recs)
    if joint:
        out['fit3_sup'] = {k: v['fit3']['sup_margin'] for k, v in joint.items() if 'fit3' in v}
        out['far'] = {k: v['far']['max_dist'] for k, v in joint.items() if v.get('far')}
    open(os.path.join(RES, 'pocket251.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    json.dump(out, open(os.path.join(RES, 'pocket251_summary.json'), 'w', encoding='utf-8'), indent=1)
    print('wrote results/pocket251.md')
    for k, v in out.items():
        print(' ', k, v)


if __name__ == '__main__':
    main()
