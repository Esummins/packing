"""A247: results/walk247.md from the result files (catalogue, pair table, walk counts, triples).
    python summarise247.py
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ATT = os.path.abspath(os.path.join(HERE, '..'))
R = os.path.join(ATT, 'results')


def rows(name):
    p = os.path.join(R, name)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []


def summary(name):
    r = rows(name)
    return r[0] if r and r[0].get('kind') == 'summary' else {}


def fmt(n):
    return '{:,}'.format(n).replace(',', ' ') if isinstance(n, int) else str(n)


def main():
    L = ['# A247 -- the perimeter walk: results', '', 'Generated by `code/summarise247.py`.  Note: `docs/proofs/perimeter_walk.md`.', '']
    cat = rows('catalogue247.jsonl')
    nec = [r for r in cat if r.get('kind') == 'necessity']
    L += ['## 1. The catalogue', '',
          '* monotone form (level 1e-3): %d meeter sets, %d free sets, all FEASIBLE with exact rational witnesses; the %d minimal '
          'cell pairs outside every N_c all INFEASIBLE (eta = 0, window and corpus range): %s' % (
              sum(1 for r in cat if r.get('kind') == 'M'), sum(1 for r in cat if r.get('kind') == 'F'),
              nec[0]['n_bad_pairs'] if nec else 0, nec[0]['all_infeasible'] if nec else None)]
    for tag in ('exact_0.05', 'exact_0.02'):
        c = rows('catalogue247_%s.jsonl' % tag)
        if c:
            st = collections.Counter(r['status'] for r in c if r.get('kind') in ('M', 'F'))
            L.append('* exact form %s (avoid level %s): %s' % (tag, c[1].get('eta_avoid') if len(c) > 1 else '?', dict(st)))
    corp = [r for r in cat if r.get('kind') == 'corpus']
    if corp:
        L.append('* corpus (monotone catalogue): %d (square, tol) pairs, violations %d, max cells %d' % (
            corp[0]['squares_checked'], len(corp[0]['violations']), corp[0]['max_cells']))
    L += ['', '## 2. The pair table (exact form, window [3.82, s-hat])', '']
    for fn in sorted(os.listdir(R)):
        if fn.startswith('pairs247_'):
            pr = rows(fn)
            st = collections.Counter(r['status'] for r in pr)
            kinds = collections.Counter()
            for r in pr:
                k = r['key']
                nf = k.count('F:')
                kind = 'FF' if nf == 2 else 'MF' if nf == 1 else ('MM-same' if k.split(' | ')[0][2:4] == k.split(' | ')[1][2:4] else 'MM-adj/opp')
                kinds[(kind, r['status'])] += 1
            lv = (pr[0]['eta'], pr[0].get('eta_avoid')) if pr else None
            L.append('* `%s`: level %s, %d pairs: %s' % (fn, lv, len(pr), dict(st)))
            L.append('  * by kind: ' + ', '.join('%s %s %d' % (k, s, n) for (k, s), n in sorted(kinds.items())))
            inf = [r['key'] for r in pr if r['status'] == 'INFEASIBLE']
            if inf:
                L.append('  * certified kills: ' + '; '.join('`%s`' % k for k in inf))
    L += ['', '## 3. The walks (transfer-matrix counts of labelled walks; up to D4 divide by at most 8)', '',
          '| facts | corner options | free multisets | labelled walks | by free squares used | up to D4 | corpus check |', '|---|---|---|---|---|---|---|']
    for fn in sorted(os.listdir(R)):
        if fn.startswith('walks247_'):
            s = summary(fn)
            if not s:
                continue
            facts = 'lemmas' + (' + SLOT-MET' if s.get('slotmet') else '') + (' + type-F [C]' if s.get('type_f') else '') + \
                (' + pairs (%d kills)' % s['n_infeasible_pairs'] if s.get('n_infeasible_pairs') else '')
            co = s.get('corner_options', {})
            corpus = ('%d/%d allowed' % (s['corpus_allowed'], s['corpus_checked'])) if 'corpus_checked' in s else ''
            L.append('| %s (level %s) | %s | %s | %s | %s | %s | %s |' % (
                facts, s.get('eta'), co.get('BL', '?'), fmt(s.get('free_multisets', '?')), fmt(s['raw_walks']),
                ' '.join('%s:%s' % (k, fmt(v)) for k, v in sorted(s.get('raw_by_free_used', {}).items())),
                fmt(s['walks_d4']) if s.get('walks_d4') is not None else '(not listed)', corpus))
    L += ['', '## 4. The triples', '']
    for fn in sorted(os.listdir(R)):
        if fn.startswith('triples247_'):
            tr = rows(fn)
            st = collections.Counter(r['status'] for r in tr)
            L.append('* `%s`: %d triples: %s; walks killed (of the listed set): %d' % (
                fn, len(tr), dict(st), sum(r.get('walks', 0) for r in tr if r['status'] == 'INFEASIBLE')))
            for r in tr:
                if r['status'] == 'INFEASIBLE' or 'monotone' in r['key']:
                    L.append('  * %s: `%s` (%d boxes, %.0f s)' % (r['status'], r['key'], r['boxes'], r['seconds']))
    with open(os.path.join(R, 'walk247.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
