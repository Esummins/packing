"""A94 -- depgraph edits (run once at close-out, after `git pull`): chip A94 on C.A57; notes on
C.A57, C.K4TIER, K0.SLIDE, K0.CW; then render the SVG.  Idempotent (a note is appended only once).
Usage: python depgraph_note94.py "<A94 headline for C.A57>" "<C.K4TIER note>"
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
P = os.path.join(ROOT, "lean", "depgraph.json")

NOTE_SLIDE = ("A94 (2026-09-04): the d2 form of SLIDE needs the JOINT translation of all shallow "
              "intruders (one cluster generated by Q1..Qk, moved by sqrt2*d2, side cost exactly d2); the "
              "sequential proof gives only the SUM bound. Slot form (pinned classes, pin blocks move with their "
              "walls, Lemma SWEEP): docs/proofs/slot_crowds.md sect 3.")
NOTE_CW = ("A94 (2026-09-04): slot form CS(S; s, m_lo; delta, e) for pinned classes = same two-run scheme "
           "with pin cores slackened by rho >= (lambda-1) A_S, slot families in the slot frames with pad "
           "(lambda-1)(a + 1/sqrt2 + max(i,j)), and r_max runs B_r (incidence budget N + 2 m_u e); "
           "docs/proofs/slot_crowds.md sect 4.")


def add_note(n, text):
    if text in (n.get("note") or ""):
        return
    n["note"] = ((n.get("note") or "") + " || " + text).strip(" |")


def main():
    a57_note, k4_note = sys.argv[1], sys.argv[2]
    d = json.load(open(P, encoding="utf-8"))
    for n in d["nodes"]:
        if n["id"] == "C.A57":
            n["owner"] = "A96"   # chip released to A96 (parametric pass) at A94 close-out
            add_note(n, a57_note)
            src = n.get("source", "")
            if "slot_crowds" not in src:
                n["source"] = src + "; docs/proofs/slot_crowds.md + attempts/A94-slot-crowds (slot-crowd chain)"
        elif n["id"] == "C.K4TIER":
            add_note(n, k4_note)
        elif n["id"] == "K0.SLIDE":
            add_note(n, NOTE_SLIDE)
        elif n["id"] == "K0.CW":
            add_note(n, NOTE_CW)
    d["meta"]["attempt"] = (d["meta"].get("attempt", "") +
                            " || A94 (2026-09-04): slot-crowd chain for the pinned classes (C.A57 chip -> A94; "
                            "C.K4TIER Trump-image ceiling note; K0.SLIDE joint-translation note).")
    json.dump(d, open(P, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    subprocess.run([sys.executable, os.path.join(ROOT, "lean", "render_depgraph.py")], check=True)
    print("depgraph updated + rendered")


if __name__ == "__main__":
    main()
