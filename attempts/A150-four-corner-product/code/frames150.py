"""A150 -- the four corner frames, the D4 action on 4-tuples, and the global box of a local cell.

LOCAL FRAMES (orientation-consistent: each is the BL frame carried by a ROTATION of the container,
never a reflection, so the level-1 cell index means the same thing at every corner).  With
s = s0 and (x, y) the global centre:

    BL: (u, v) = (x, y)            global: x = u,      y = v
    BR: (u, v) = (y, s - x)        global: x = s - v,  y = u
    TR: (u, v) = (s - x, s - y)    global: x = s - u,  y = s - v
    TL: (u, v) = (s - y, x)        global: x = v,      y = s - u

A unit square is invariant under a quarter turn, so the TILT WINDOW of a cell is the same number in
every frame: theta mod 90 is the pose invariant, and the four frames differ by multiples of 90.

D4 ON 4-TUPLES.  Write a state as t = (t_BL, t_BR, t_TR, t_TL), each t_c a local cell index
(ix, iy, it).  The container's D4 is generated by

    r  = quarter turn (x, y) -> (s - y, x):  BL->BR->TR->TL->BL, local indices UNCHANGED
         (r is orientation preserving and carries each local frame onto the next);
    m  = reflection in y = x:  fixes BL and TR, swaps BR and TL, and acts on EVERY local index by
         the transpose  T(ix, iy, it) = (iy, ix, NTILT-1-it)  (m is orientation reversing, so in
         each local frame it is the BL transpose of A143's Lemma K0-D4).

so  r(t) = (t_TL, t_BL, t_BR, t_TR)   (t'_{g(c)} = t_c)
    m(t) = (T t_BL, T t_TL, T t_TR, T t_BR).

The remaining six elements are products.  Because T has NO fixed cell (T(a) = a needs ix = iy and
it = 5 - it, impossible for an integer it in 0..5), the two DIAGONAL reflections fix no 4-tuple at
all, which is what makes the D4 quotient of the product very close to an exact division by 8.
"""
