import cells143 as C                                            # noqa: E402
from caselp import Box                                          # noqa: E402

CORNERS = ("BL", "BR", "TR", "TL")
S0 = C.S0


def to_global(corner, x0, x1, y0, y1):
    """local centre box -> global centre box (the tilt window is unchanged, mod 90)."""
    s = S0
    if corner == "BL":
        return (x0, x1, y0, y1)
    if corner == "BR":
        return (s - y1, s - y0, x0, x1)
    if corner == "TR":
        return (s - x1, s - x0, s - y1, s - y0)
    if corner == "TL":
        return (y0, y1, s - x1, s - x0)
    raise ValueError(corner)


def global_box(corner, cell):
    b = cell.box
    X0, X1, Y0, Y1 = to_global(corner, b.x0, b.x1, b.y0, b.y1)
    return Box(X0, X1, Y0, Y1, b.th0, b.th1)


def global_subbins(corner, cell, nsub=4):
    out = []
    for (a, b, cl) in C.subbin_clip(*cell.raw, nsub=nsub):
        X0, X1, Y0, Y1 = to_global(corner, cl[0], cl[1], cl[2], cl[3])
        out.append(Box(X0, X1, Y0, Y1, a, b))
    return out


def T(k):
    return (k[1], k[0], C.NTILT - 1 - k[2])


# --------------------------------------------------------------- the eight elements of D4
def g_e(t):
    return t


def g_r(t):
    return (t[3], t[0], t[1], t[2])


def g_r2(t):
    return (t[2], t[3], t[0], t[1])


def g_r3(t):
    return (t[1], t[2], t[3], t[0])


def g_m(t):            # y = x : fixes BL, TR; swaps BR, TL
    return (T(t[0]), T(t[3]), T(t[2]), T(t[1]))


def g_m2(t):           # y = -x : fixes BR, TL; swaps BL, TR
    return (T(t[2]), T(t[1]), T(t[0]), T(t[3]))


def g_h(t):            # y -> s - y : swaps BL<->TL, BR<->TR
    return (T(t[3]), T(t[2]), T(t[1]), T(t[0]))


def g_v(t):            # x -> s - x : swaps BL<->BR, TL<->TR
    return (T(t[1]), T(t[0]), T(t[3]), T(t[2]))


D4 = (("e", g_e), ("r", g_r), ("r2", g_r2), ("r3", g_r3),
      ("m_diag", g_m), ("m_anti", g_m2), ("m_horiz", g_h), ("m_vert", g_v))


def canonical(t):
    return min(g(t) for _n, g in D4)
