"""A134 T3 -- emit the `pcert` of a `local-cert-t-v2` certificate as a Lean scratch file and let
`native_decide` run `LocalCertT2`'s own checks on it.

    python gen_pcert_lean.py <path.t2cert.json.gz> <out.lean> [--families h,S,w] [--limit N]

This closes the loop generator -> Lean: the file it writes contains the certificate's positivity
certificates as `ℚ` literals and asserts

    s07H.all hOk = true      (posChain on hPoly)
    s07S.all sOk = true      (posChain on sUpPoly / sLoPoly, five chains per entry)
    s07W.all wOk = true      (posGrid on wPolyT, or posChain on its substitution at a pin)

by `native_decide`.  A133/A126's finding was that the ELABORATOR, not the kernel, is the wall at
10^5-10^6 coefficients; `--limit` exists to measure the wall as a function of the entry count.
"""
from __future__ import annotations

import argparse, gzip, json, os, time
from fractions import Fraction as Q


def q(s):
    v = Q(s)
    return "(%d : ℚ)" % v.numerator if v.denominator == 1 else "((%d : ℚ) / %d)" % (v.numerator, v.denominator)


def qlist(xs):
    return "[" + ", ".join(q(x) for x in xs) + "]"


def chain1(pcs):
    return "[" + ", ".join("(%s, %s, %s)" % (q(a), q(b), qlist(c)) for (a, b, c) in pcs) + "]"


def grid2(g):
    cols = []
    for (a, b, ys) in g:
        rows = "[" + ", ".join(
            "(%s, %s, [%s])" % (q(c), q(d), ", ".join(qlist(r) for r in C)) for (c, d, C) in ys) + "]"
        cols.append("(%s, %s, %s)" % (q(a), q(b), rows))
    return "[" + ", ".join(cols) + "]"


HEAD = """import PackingCertMathlib.LocalCertT2

/-!
# A134 T3 -- the emitted positivity certificates, replayed by `native_decide`

Auto-generated by `attempts/A134-certcover-close/code/gen_pcert_lean.py` from
`%s`.  Do not edit by hand.

Every entry of the certificate's envelope table is here with the positivity certificate the
generator emitted for it, and the three theorems below run `LocalCertT2.posChain` / `posGrid` on
all of them.  A passing `native_decide` is the statement that Lean's own decidable checks accept
the certificate the generator wrote -- the loop generator -> checker -> kernel, closed.
-/

namespace PackingCert
namespace S11
namespace LocalCertT2
namespace A134Data

set_option maxHeartbeats 2000000

open PackingCert.S11.LocalCertT
open PackingCert.S11.LocalCertT2

structure HEnt where
  m : ℚ
  c : ℚ
  a : ℚ
  b : ℚ
  pcs : List (ℚ × ℚ × List ℚ)

def hOk (e : HEnt) : Bool := posChain (hPoly e.m e.c) e.pcs e.a e.b

structure SEnt where
  cm : ℚ
  sm : ℚ
  alpha : ℚ
  bup : ℚ
  blo : ℚ
  shi : ℚ
  slo : ℚ
  K : ℚ
  a : ℚ
  b : ℚ
  up : List (ℚ × ℚ × List ℚ)
  lo : List (ℚ × ℚ × List ℚ)
  chi : List (ℚ × ℚ × List ℚ)
  clo : List (ℚ × ℚ × List ℚ)
  corr : List (ℚ × ℚ × List ℚ)

def sOk (e : SEnt) : Bool :=
  posChain (sUpPoly e.cm e.sm e.alpha e.bup) e.up e.a e.b &&
  posChain (sLoPoly e.cm e.sm e.alpha e.blo) e.lo e.a e.b &&
  posChain (sUpPoly e.cm e.sm 0 e.shi) e.chi e.a e.b &&
  posChain (sLoPoly e.cm e.sm 0 e.slo) e.clo e.a e.b &&
  posChain (cPoly e.cm e.sm e.K) e.corr e.a e.b

structure WEnt where
  eps : ℚ
  mw : ℚ
  mo : ℚ
  c : ℚ
  aw : ℚ
  bw : ℚ
  ao : ℚ
  bo : ℚ
  mode : Nat                     -- 0 = the box, 1 = t_o pinned to 0, 2 = t_w pinned to 0
  grid : List (ℚ × ℚ × List (ℚ × ℚ × List (List ℚ)))
  pcs : List (ℚ × ℚ × List ℚ)

def wOk (e : WEnt) : Bool :=
  match e.mode with
  | 0 => posGrid (wPolyT e.eps e.mw e.mo e.c) e.grid e.aw e.bw e.ao e.bo
  | 1 => posChain (padZ 5 (substY0 (wPolyT e.eps e.mw e.mo e.c))) e.pcs e.aw e.bw
  | _ => posChain (substX0 (wPolyT e.eps e.mw e.mo e.c)) e.pcs e.ao e.bo

"""

TAIL = """
/-- Every `h` chord of the certificate is certified. -/
theorem hAll : dH.all hOk = true := by native_decide

/-- Every `S` envelope, McCormick corner and correction constant is certified. -/
theorem sAll : dS.all sOk = true := by native_decide

/-- Every `w` plane is certified, on the box or at the pinned tilt. -/
theorem wAll : dW.all wOk = true := by native_decide

end A134Data
end LocalCertT2
end S11
end PackingCert
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cert")
    ap.add_argument("out")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--per", type=int, default=32, help="entries per batched definition")
    args = ap.parse_args()
    with gzip.open(args.cert, "rt", encoding="utf-8") as f:
        c = json.load(f)
    env, pc = c["env"], c["pcert"]
    t0 = time.time()

    def cap(items):
        items = sorted(items)
        return items[:args.limit] if args.limit else items

    H = []
    for key in cap((pc["h"] or {}).keys()):
        m, cc = env["h"][key]
        a, b = key.split("|")
        H.append("⟨%s, %s, %s, %s, %s⟩" % (q(m), q(cc), q(a), q(b), chain1(pc["h"][key])))
    S = []
    for key in cap((pc["S"] or {}).keys()):
        al, bu, bl = env["S"][key]
        a, b = key.split("|")
        r = pc["S"][key]
        tm = Q(r["tm"])
        cm, sm = (1 - tm * tm) / (1 + tm * tm), 2 * tm / (1 + tm * tm)
        S.append("⟨%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s⟩"
                 % (q(cm), q(sm), q(al), q(bu), q(bl), q(r["s_hi"]), q(r["s_lo"]), q(r["K"]),
                    q(a), q(b), chain1(r["up"]), chain1(r["lo"]), chain1(r["c_hi"]),
                    chain1(r["c_lo"]), chain1(r["corr"])))
    W = []
    for key in cap((pc["w"] or {}).keys()):
        mw, mo, cc = env["w"][key]
        parts = key.split("|")
        eps, aw, bw, ao, bo = parts[0], parts[1], parts[2], parts[3], parts[4]
        r = pc["w"][key]
        if r["mode"] == "xy":
            mode, g, p = 0, grid2(r["x"]), "[]"
        elif r["mode"] == "x":
            mode, g, p = 1, "[]", chain1(r["p"])
        else:
            mode, g, p = 2, "[]", chain1(r["p"])
        W.append("⟨%s, %s, %s, %s, %s, %s, %s, %s, %d, %s, %s⟩"
                 % (q(eps), q(mw), q(mo), q(cc), q(aw), q(bw), q(ao), q(bo), mode, g, p))

    def chunked(name, ty, items, per):
        """A126's batching: groups of `per` entries, concatenated linearly.  Elaborating ONE list
        literal of 10^4-10^5 numerals is where a generated file of this size dies; the kernel is
        never the wall."""
        out, parts = [], []
        for i in range(0, len(items), per):
            nm = "%s%d" % (name, i // per)
            parts.append(nm)
            out.append("private def %s : List %s := [\n  %s]\n"
                       % (nm, ty, ",\n  ".join(items[i:i + per])))
        if not parts:
            out.append("def %s : List %s := []\n" % (name, ty))
        else:
            out.append("def %s : List %s := %s\n" % (name, ty, " ++ ".join(parts)))
        return "\n".join(out) + "\n"

    body = HEAD % c["meta"]["id"]
    body += chunked("dH", "HEnt", H, args.per)
    body += chunked("dS", "SEnt", S, args.per)
    body += chunked("dW", "WEnt", W, args.per)
    body += TAIL
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(body)
    print("%s -> %s  h %d  S %d  w %d  %.2f MB  %.1f s"
          % (c["meta"]["id"], args.out, len(H), len(S), len(W),
             os.path.getsize(args.out) / 1e6, time.time() - t0))


if __name__ == "__main__":
    main()
