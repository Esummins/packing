"""A252: results/disc252.md (+ disc252_summary.json) from adv252.json, poker252_*.json,
lemmas252.json and the s-hat ring.  Safe on partial results (the ladder is detached)."""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ATT = os.path.abspath(os.path.join(HERE, '..'))
RES = os.path.join(ATT, 'results')
sys.path.insert(0, HERE)
import disc252 as D                                                   # noqa: E402

R3 = D.R3


def load(name):
    fn = os.path.join(RES, name)
    return json.load(open(fn, encoding='utf-8')) if os.path.exists(fn) else None


def rows(name):
    fn = os.path.join(RES, name)
    if not os.path.exists(fn):
        return []
    return [json.loads(l) for l in open(fn, encoding='utf-8') if l.strip()]


def main():
    best = load('adv252.json') or {}
    lem = load('lemmas252.json') or {}
    pk = load('poker252_shat.json')
    pkrows = load('poker252_rows.json') or {}
    prot = rows('poker252.jsonl')
    L = ['# A252 -- CENTRE-DISC: the centre set of the ring pocket, the flat-corner refutation, the poker',
         '', 'Generated by `summarise252.py`.  Sources: `adv252.jsonl/json` (the adversarial ladder over the ring',
         'family), `poker252_shat.json` / `poker252_rows.json` / `poker252.jsonl` (the poker of the corrected',
         'family-stuck ring structure), `lemmas252.json` (the closed forms).  1/sqrt3 = %.5f.' % R3, '',
         '## 1. Lemma CENTRE-DISC about the container centre O: FALSE on the window', '',
         'The corner MOUTH (both touchers of one corner near the flat limit theta -> 90 deg, delta -> 1) admits the',
         'centre (3/2, 3/2) of the corner frame, at distance (s/2 - 3/2) sqrt2 from O; that exceeds 1/sqrt3 iff',
         's > 3 + 2/sqrt6 = %.5f.  Measured on FEASIBLE rings (margin >= 0):' % D.S_FLAT, '',
         '| side | metric | best feasible value | ring margin | far point | contacts | sec_r | halves | disp3 | diam |',
         '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    summ = {'three_disc_radius': R3, 's_flat': D.S_FLAT, 'rows': {}}
    for key in sorted(best):
        r = best[key]
        m = r['metrics']
        c = ', '.join('%s %.3f' % (n, v) for n, v in m.get('contacts', [])[:2])
        fp = '(%.3f, %.3f)' % tuple(m['far_pt']) if m.get('far_pt') else '-'
        L.append('| %s | %s | %.4f | %+.4f | %s | %s | %.4f | %.4f | %.4f | %.4f |' % (
            r['side'], r['metric'], r['value'], r['margin'], fp, c, m.get('sec_r', 0), m.get('halves_diam', 0),
            m.get('disp3', 0), m.get('diam', 0)))
        summ['rows'][key] = {'value': r['value'], 'margin': r['margin'], 'sec_r': m.get('sec_r'),
                             'halves': m.get('halves_diam'), 'disp3': m.get('disp3'), 'diam': m.get('diam')}
    far_rows = [r for r in best.values() if r['metric'] == 'far_O' and r['margin'] >= 0]
    refuted = [r for r in far_rows if r['value'] > R3]
    summ['far_O_refuted_sides'] = sorted(r['side'] for r in refuted)
    L += ['', '**far_O > 1/sqrt3 on feasible rings at sides: %s** (sides searched: %s).' % (
        ', '.join(summ['far_O_refuted_sides']) or 'none yet', ', '.join(sorted({r['side'] for r in far_rows})) or 'none yet')]
    if lem:
        L += ['', '## 2. The closed forms (`lemmas252.py`)', '',
              '| item | value |', '| --- | --- |',
              '| flat limit (s/2 - 3/2) sqrt2 | %s |' % ', '.join('%s: %.4f' % (k, v) for k, v in lem.get('flat_limit_far', {}).items()),
              '| threshold s_flat | %.5f |' % lem.get('s_flat', D.S_FLAT),
              '| NOTCH-SEP min phi | %.4f at %.2f deg |' % tuple(lem.get('phi_min', (0, 0))),
              '| mouth max over the box grid vs flat limit | %s |' % '; '.join(
                  '%s: %.4f vs %.4f' % (k, v['value'], v['flat_limit']) for k, v in lem.get('mouth_box_max', {}).items()),
              '| contact census at the far points (kinds) | %s over %d rows |' % (lem.get('contact_census'), lem.get('contact_rows', 0))]
    L += ['', '## 3. The corrected family-stuck ring structure: ring + POKER (coordinator, 2026-09-18 00:30)', '']
    if pk:
        a = pk['anchored']
        L += ['At A249\'s exact ring at s-hat: poker margin %+.5f (A249: +0.0017), pose (%.3f, %.3f, %.1f deg) on wall %s;' % (
              pk['poke_margin'], pk['pose'][0], pk['pose'][1], math.degrees(pk['pose'][2]), pk['wall']),
              'per wall %s.  With the poker in place the residual centre set is %s (area %.4f, diameter %.4f):' % (
              {k: round(v, 5) for k, v in pk['per_wall'].items()}, 'EMPTY' if a['residual_C_area'] < 1e-9 else 'non-empty',
              a['residual_C_area'], a['residual_diam']),
              '**no second free square fits beside the poker at s-hat: capacity 1, 8 + 1 = 9 < 11.**']
        summ['shat'] = {'poke_margin': pk['poke_margin'], 'residual_area': a['residual_C_area'], 'residual_diam': a['residual_diam']}
    if pkrows:
        L += ['', 'The adversarial rings of s.1 against the poker (does the far ring admit the poker at all?):', '',
              '| side | metric | value | ring margin | best poker margin | wall | residual C diam |', '| --- | --- | --- | --- | --- | --- | --- |']
        for key in sorted(pkrows):
            r = pkrows[key]
            rd = '-' if r['anchored'] is None else '%.4f' % r['anchored']['residual_diam']
            L.append('| %s | %s | %.4f | %+.4f | %+.4f | %s | %s |' % (key.split('|')[0], key.split('|')[1], r['value'], r['ring_margin'], r['poke_margin'], r['wall'], rd))
        summ['poker_rows'] = {k: {'poke_margin': v['poke_margin'], 'value': v['value']} for k, v in pkrows.items()}
    if prot:
        L += ['', 'PROTECTED adversary (ring + poker jointly feasible, margin >= 0; best per side and metric):', '',
              '| side | metric | best value | joint margin | residual C diam | far part diam |', '| --- | --- | --- | --- | --- | --- |']
        bestp = {}
        for r in prot:
            if r['margin'] >= 0:
                k = (r['side'], r['metric'])
                if k not in bestp or r['value'] > bestp[k]['value']:
                    bestp[k] = r
        for k in sorted(bestp):
            r = bestp[k]
            a = r['anchored'] or {}
            L.append('| %s | %s | %.4f | %+.4f | %.4f | %.4f |' % (k[0], k[1], r['value'], r['margin'],
                     a.get('residual_diam', 0), a.get('far_part_diam', 0)))
        summ['protected'] = {'%s|%s' % k: {'value': v['value'], 'margin': v['margin'],
                                            'residual_diam': (v['anchored'] or {}).get('residual_diam')} for k, v in bestp.items()}
        summ['protected_rows'] = len(prot)
    L += ['', '## 4. Verdict', '',
          '* [F] CENTRE-DISC about O (A251 s.3, the brief\'s target) -- the flat-corner mouth; every INRADIUS-only',
          '  (disc) criterion is also broken in the flat-flat corner limit, where the corner NOTCH holds a disc of',
          '  radius 1/2 but no unit square (see `docs/proofs/centre_disc.md` s.3).',
          '* [T] the criteria that remain (any n): C inside SOME disc of radius < 1/sqrt3, or two pieces of diameter < 1,',
          '  or the POKER-ANCHORED form (the residual centre set beside the pinned poker has diameter < 1) => capacity <= 2.',
          '* [T-computed] at s-hat the residual centre set is empty; [M] the ladder rows above.',
          '* [C] RING-POKER-RESIDUAL(11) over the family -- FAMILY-STUCK-EXIST(11) is NOT closed; k0_00 unchanged.']
    open(os.path.join(RES, 'disc252.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    json.dump(summ, open(os.path.join(RES, 'disc252_summary.json'), 'w', encoding='utf-8'), indent=1)
    print('\n'.join(L[-8:]))


if __name__ == '__main__':
    main()
