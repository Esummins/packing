def hyp_at(cls, m_fr, spec, delta=0.0):
    """delta = 0 -> A53's degenerate pin boxes (core half-side a = 1/2 - O(1e-7)).

    delta > 0 -> SLACK CORES (A63 route (b) / A57 grid.py): a centre box of half-width
    w = delta/sqrt(2) makes caselp's core half-side a = 1/2 - delta, so the certificate's
    Lemma-B dilation shell rho = 1/2 - a*(cos tm + sin tm) ~ delta - tm and one certified
    side s'' covers the packing sides ( s''/(1 + rho/A), s'' ] with A = 5/2.  The box
    hypothesis is WEAKER than the exact-slot one (it admits a neighbourhood of skeletons),
    so a kill of the box kills the exact stratum a fortiori -- but the exempt region shrinks
    with a, so tau RISES.  That price is what --delta measures."""
    pins = pins_at(cls, m_fr, spec)
    w = float(delta) / math.sqrt(2.0)
    boxes = [Box(float(x) - w, float(x) + w, float(y) - w, float(y) + w, 0.0, 0.0)
             for (x, y) in pins]
    return Hyp(boxes, []), pins


def shell(delta, s_side, tm=1.0 / (1 << 25), A=2.5):
    """(rho, lo) -- the A63 B' slab ( lo, s_side ] a delta-core certificate at s_side covers."""
    a = 0.5 - float(delta)
    c = (1 - tm * tm) / (1 + tm * tm)
    sn = 2 * tm / (1 + tm * tm)
    rho = 0.5 - a * (c + sn)
    return rho, float(s_side) / (1 + rho / A)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cls", required=True)
    ap.add_argument("--sides", nargs="*", default=SIDES)
    ap.add_argument("--lp_time", type=float, default=600.0)
    ap.add_argument("--max_iter", type=int, default=200)
    ap.add_argument("--max_cols_add", type=int, default=150)
    ap.add_argument("--max_atoms", type=int, default=2500,
                    help="cap on the carried column pool (A61 M1: the LP matrix is dense "
                         "rows x orbits)")
    ap.add_argument("--headroom", type=float, default=6.0)
    ap.add_argument("--headroom_wait", type=float, default=7200)
    ap.add_argument("--tag", default="")
    ap.add_argument("--delta", type=float, default=0.0,
                    help="slack-core half-side deficit (a = 1/2 - delta); 0 = A53 pins")
    a = ap.parse_args()

    cls = a.cls
    spec = load_spec()
    cl = spec["classes"][cls]
    k, budget = cl["k"], 11 - cl["k"]
    assert budget == cl["N"], "budget/N mismatch for %s" % cls

    out_p = os.path.join(BASE, "results", "scan_%s%s.json" % (cls, a.tag))
    nodes = os.path.join(BASE, "results", "nodes")
    os.makedirs(nodes, exist_ok=True)
    lf = open(os.path.join(BASE, "logs", "scan_%s%s.log" % (cls, a.tag)), "a",
              buffering=1, encoding="utf-8")

    def log(*x):
        print(*x, file=lf, flush=True)
        print(*x, flush=True)

    # TRUMP CANARY applicability: the canary is "at every side >= s-hat the family fits and
    # the LP saturates".  It binds only on classes whose pin pattern IS realised by a Trump
    # image (A65 crowdfam verified=true).  corners4 (k4_13) has NO Trump image at all (A71
    # G_S = empty; crowdfam found no feasible pins+7-family at s0), so its LP is legitimately
    # ABOVE the budget there and the canary is not applicable to it.
    cf = json.load(open(CROWDFAM))["classes"].get(cls, {})
    trump_realised = bool(cf.get("verified"))
    sides_all = sorted({Fr(s) for s in a.sides})

    rho, slab_lo = shell(a.delta, float(min(sides_all))) if a.delta > 0 else (None, None)
    rec = {"cls": cls, "k": k, "budget": budget, "lp_time": a.lp_time,
           "delta": a.delta, "shell_rho": rho,
           "solver": "A53/A54/A60 caselp+lpbox (copied); C1/D4 per pin symmetry",
           "trump_realised": trump_realised,
           "crowdfam_source": cf.get("source"), "crowdfam_min_side": cf.get("catalogue_min_side"),
           "started": time.strftime("%Y-%m-%dT%H:%M:%S"), "s_hat": S_HAT,
           "canary": [], "rows": []}
    # sort DESCENDING (s0 first: the Trump canary side)
    sides = sorted({Fr(s) for s in a.sides}, reverse=True)
    log("=== A82 scan %s: k=%d budget=%d, %d sides (descending), lp_time=%gs, "
        "trump_realised=%s" % (cls, k, budget, len(sides), a.lp_time, trump_realised))

    # resume: keep sides already measured in a previous run of this cell
    done = {}
    if os.path.exists(out_p):
        try:
            prev = json.load(open(out_p))
            if prev.get("cls") == cls and prev.get("budget") == budget:
                done = {r["side"]: r for r in prev.get("rows", [])}
                rec["rows"] = [done[s] for s in sorted(done, key=lambda z: -float(Fr(z)))]
                rec["resumed_from"] = prev.get("started")
                rec["canary"] = prev.get("canary", [])
        except Exception:
            done = {}

    warm = None
    for m_fr in sides:
        if str(m_fr) in done:
            log("  m=%s already measured (tau=%.6f); skipping"
                % (m_fr, done[str(m_fr)]["tau"]))
            np_ = os.path.join(nodes, "%s%s_%s.json"
                               % (cls, a.tag, str(m_fr).replace("/", "_")))
            if os.path.exists(np_):
                try:
                    prev_res = json.load(open(np_))
                    warm = dict(atoms=[(p[0], p[1]) for p in prev_res["atoms_all"]], rows=[])
                except Exception:
                    pass
            continue
        m = float(m_fr)
        hyp, pins = hyp_at(cls, m_fr, spec, a.delta)
        sym = "D4" if hyp.is_symmetric_D4(m) else "C1"
        g = wait_headroom(a.headroom, poll=60, max_wait=a.headroom_wait, log=log)
        log("  m=%s (%.9f) sym=%s pins=%s headroom=%.2fGB"
            % (m_fr, m, sym, [(str(x), str(y)) for x, y in pins], g))
        t0 = time.time()
        res = caselp.solve_node(m, hyp, budget, sym_kind=sym, warm=warm,
                                time_limit=a.lp_time, max_iter=a.max_iter,
                                max_cols_add=a.max_cols_add, fine=True, log=log,
                                checkpoint=os.path.join(
                                    nodes, "%s%s_%s_state.json"
                                           % (cls, a.tag, str(m_fr).replace("/", "_"))))
        dt = time.time() - t0
        tau = res["tau"]
        row = dict(side=str(m_fr), side_float=m, sym=sym, tau=tau,
                   eta=tau - budget, converged=bool(res["converged"]),
                   a39_gate=bool(tau * 1.005 < budget),
                   kill_law_eta_le_m1=bool(tau - budget <= -1.0),
                   delta=a.delta,
                   shell=(list(shell(a.delta, m)) if a.delta > 0 else None),
                   n_orbits=res["n_orbits"], n_rows=res["n_rows"],
                   minmass=res.get("minmass"), maxcov=res.get("maxcov"),
                   seconds=round(dt, 1))
        rec["rows"].append(row)
        json.dump(rec, open(out_p, "w"), indent=1)
        # keep the node json of every side: the certificate is emitted from one of them
        res["skeleton_name"] = "%s@%s" % (cls, m_fr)
        res["skeleton_slots"] = [[float(x), float(y)] for (x, y) in pins]
        res["side_rational"] = str(m_fr)
        res["k"] = k
        json.dump(res, open(os.path.join(
            nodes, "%s%s_%s.json" % (cls, a.tag, str(m_fr).replace("/", "_"))), "w"))
        log("  >>> %s m=%-16s tau=%.6f eta=%+.6f conv=%s A39=%s orbits=%d rows=%d (%.0fs)"
            % (cls, str(m_fr), tau, tau - budget, res["converged"], row["a39_gate"],
               res["n_orbits"], res["n_rows"], dt))
        # TRUMP CANARY: at every side >= s-hat a Trump-realised class must SATURATE
        # (tau >= budget: the Trump family is a strictly separated budget-size family, so the
        # disjoint-family bound forces tau* >= budget).  tau ABOVE the budget is not a
        # violation (corners4 sits there legitimately); tau BELOW it on a converged LP is.
        if m >= S_HAT:
            sat = tau >= budget - 1e-3
            can = dict(side=str(m_fr), tau=tau, budget=budget, saturated=bool(sat),
                       converged=bool(res["converged"]), applicable=trump_realised)
            rec["canary"].append(can)
            json.dump(rec, open(out_p, "w"), indent=1)
            if trump_realised and not sat:
                if res["converged"]:
                    rec["CANARY_FAIL"] = (
                        "at m=%s >= s_hat the CONVERGED LP gave tau=%.6f < budget %d: the "
                        "Trump family fits there, so tau* >= budget -- normalisation is wrong"
                        % (m_fr, tau, budget))
                    json.dump(rec, open(out_p, "w"), indent=1)
                    log("  !!! " + rec["CANARY_FAIL"])
                    return 4
                log("  !!! CANARY WARNING: tau=%.6f < budget %d at m=%s but the LP did NOT "
                    "converge (restricted master under-estimates tau*); continuing"
                    % (tau, budget, m_fr))
                rec.setdefault("canary_warnings", []).append(can)
        # column-only warm start for the next (smaller) side
        atoms = [(p[0], p[1]) for p in res["atoms_all"]]
        seen, cols = set(), []
        for p in atoms:
            kk = (round(p[0], 7), round(p[1], 7))
            if kk not in seen:
                seen.add(kk)
                cols.append(p)
        if len(cols) > a.max_atoms:
            step = max(1, len(cols) // a.max_atoms)
            cols = cols[::step][:a.max_atoms]
        warm = dict(atoms=cols, rows=[])

    rec["finished"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    json.dump(rec, open(out_p, "w"), indent=1)
    log("wrote %s" % out_p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
