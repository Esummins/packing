r"""
A82 (b)/(c) -- the conditioned case-LP tau(m) down the side ladder.

For a protected class and a side m: pins at m's OWN slots (A56 P0/P1 window semantics,
sides82.rebase), budget = 11 - k, and the ordinary node guard LP
    tau(m) = min mu(total)  s.t. mu(Q) >= 1 for every admissible placement in [0,m]^2 that
             is not provably meeting a pin core.
Reported per side:
    eta(m)  = tau(m) - budget                     (A60 certification law: kill wants eta <= -1)
    A39 gate: tau * 1.005 < budget                (certify's minimum scale headroom)

Sides are walked DESCENDING with COLUMN-ONLY warm starts (the atoms of the previous side's
optimum are legal placements-of-mass at the next side down only after re-admission, which
add_row/add_col re-checks; rows are NOT carried, because a row is a demand at a placement
that may be inadmissible at the smaller side and the row set is regenerated by the oracle
anyway).  Solver of record: the A53/A54/A60 lpbox+caselp (md5 2ff4907../5c59912.., copied
into this attempt so no other attempt's tree is touched).  BLAS pinned to one thread.

    python code\scan82.py --cls k4_08 --lp_time 600
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import blas1                                                        # noqa: E402,F401
import sides82                                                      # noqa: E402
from sides82 import (BASE, BOXSPEC, CROWDFAM, SIDES, S0, S_HAT, pins_at,   # noqa: E402
                     load_spec, commit_free_gb, wait_headroom)

