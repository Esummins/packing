#!/usr/bin/env python3
"""
gen_alive_lean.py -- convert an ALIVE witness JSON (output of
attempts/A57-shadow-trees/code/alivewitness.py, "result": "ALIVE-CERTIFIED") into Lean
source for the PackingCert.AliveI.checkAlive checker
(lean/PackingCertMathlib/PackingCertMathlib/AliveChecker.lean).

Usage:
    python lean/gen_alive_lean.py attempts/A57-shadow-trees/results/alive/trump5_strict.json \
        --name trump5 --side 969271/250000 \
        -o lean/PackingCertMathlib/PackingCertMathlib/AliveDataTrump5.lean

The obstacle convention is alivewitness.py's `obstacles()` verbatim: each pin slot is a
FULL closed unit square (half-side a = 1/2, tilt tm = 0) centred at the slot, snapped to
the 1e-9 grid exactly as `main()` does (`Fr(round(x*10**9), 10**9)`); an optional YES-core
box contributes one further core (kx, ky, tm, a) taken from the JSON if present.
Witness centres/tilts are copied verbatim as exact rationals (the JSON already stores them
as `Fraction` strings -- the float search layer never reaches the certificate).
"""
from __future__ import annotations

import argparse
import json
from fractions import Fraction
from pathlib import Path


def rat_lean(q: Fraction) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : Rat)"
    return f"(({q.numerator} : Rat) / {q.denominator})"


def snap9(x: float) -> Fraction:
    return Fraction(round(x * 10 ** 9), 10 ** 9)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cert")
    ap.add_argument("--name", required=True)
    ap.add_argument("--side", required=True, help="exact rational side, e.g. 969271/250000")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    d = json.loads(Path(a.cert).read_text())
    if d.get("result") != "ALIVE-CERTIFIED":
        raise SystemExit(f"not a witness file: result = {d.get('result')!r}")

    s = Fraction(a.side)
    budget = int(d["budget"])
    m = int(d["m"])
    if m != budget:
        raise SystemExit(f"m ({m}) != budget ({budget}): not an unkillability witness")

    cores = [(snap9(x), snap9(y), Fraction(0), Fraction(1, 2)) for (x, y) in d["slots"]]
    if d.get("box") is not None:
        c = d.get("core")
        if c is None:
            raise SystemExit("box present but no explicit 'core' record in the JSON")
        cores.append((Fraction(c["kx"]), Fraction(c["ky"]), Fraction(c["tm"]), Fraction(c["a"])))

    sq = [(Fraction(r["cx"]), Fraction(r["cy"]), Fraction(r["t"])) for r in d["squares"]]
    if len(sq) != budget:
        raise SystemExit(f"{len(sq)} witnesses != budget {budget}")

    # sanity: every centre in [0, s]
    for (cx, cy, t) in sq:
        assert 0 <= cx <= s and 0 <= cy <= s, (cx, cy)
        assert 0 <= t <= 1, t

    L: list[str] = []
    L.append("import PackingCertMathlib.AliveChecker")
    L.append("")
    L.append("/-!")
    L.append(f"# ALIVE witness data: `{d['name']}` (generated by `lean/gen_alive_lean.py`)")
    L.append("")
    L.append(f"Source: `{a.cert}` (`alivewitness.py`, result ALIVE-CERTIFIED).")
    L.append(f"Side `{s}`, {len(cores)} cores (pin unit squares, half-side 1/2, tilt 0),")
    L.append(f"budget {budget}, {len(sq)} witness squares.  Reported exact min gap:")
    L.append(f"`{d.get('min_gap')}` (~{d.get('min_gap_float')}).")
    L.append("-/")
    L.append("")
    L.append("namespace PackingCert.AliveData")
    L.append("")
    L.append("open PackingCert.CaseI PackingCert.AliveI")
    L.append("")
    L.append(f"def {a.name} : AliveCert :=")
    L.append("  { s := " + rat_lean(s) + ",")
    L.append("    cores :=")
    L.append("      [" + ",\n       ".join(
        "{ kx := %s, ky := %s, tm := %s, a := %s }"
        % (rat_lean(kx), rat_lean(ky), rat_lean(tm), rat_lean(aa))
        for (kx, ky, tm, aa) in cores) + "],")
    L.append(f"    budget := {budget},")
    L.append("    sq :=")
    L.append("      [" + ",\n       ".join(
        "(%s, %s, %s)" % (rat_lean(cx), rat_lean(cy), rat_lean(t))
        for (cx, cy, t) in sq) + "] }")
    L.append("")
    L.append(f"/-- The ALIVE check PASSes on `{d['name']}` (exact rational arithmetic,")
    L.append("kernel-evaluated). -/")
    L.append(f"theorem check_{a.name}_alive : checkAlive {a.name} = true := by native_decide")
    L.append("")
    L.append("end PackingCert.AliveData")
    L.append("")

    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {a.out}: {len(cores)} cores, {len(sq)} witnesses, budget {budget}, s = {s}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
