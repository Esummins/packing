#!/usr/bin/env python3
"""A216 -- the readable-layer audit: build Main + Statements, `#print axioms` every statement,
write lean/AUDIT.md.

    python lean/audit.py            # generate scratch/Audit.lean, build, run, write AUDIT.md
    python lean/audit.py --no-build # skip the `lake build` (oleans already fresh)

Scans `PackingCertMathlib/Main.lean` and `PackingCertMathlib/Statements/**/*.lean` for top-level
`theorem` / `axiom` declarations, emits `scratch/Audit.lean` (one `#print axioms` per statement),
runs it with `lake env lean` (through A78's serialised low-priority wrapper `lakeb.py`), and
tabulates: statement, file, kind, the axioms it depends on, sorry count.  Exit 1 if any statement
depends on `sorryAx`.
"""
import os, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
PROJ = os.path.join(HERE, "PackingCertMathlib")
LIB = os.path.join(PROJ, "PackingCertMathlib")
LAKEB = os.path.join(REPO, "attempts", "A78-lean-wave6", "code", "lakeb.py")
AUDIT_LEAN = os.path.join(PROJ, "scratch", "Audit.lean")
AUDIT_MD = os.path.join(HERE, "AUDIT.md")

STD = {"propext", "Classical.choice", "Quot.sound"}
DECL = re.compile(r"^(theorem|axiom)\s+([A-Za-z_][A-Za-z0-9_'.]*)", re.M)
NS = re.compile(r"^namespace\s+(\S+)", re.M)


def strip_comments(src):
    src = re.sub(r"/-.*?-/", "", src, flags=re.S)
    return re.sub(r"--.*", "", src)


def scan():
    files = [os.path.join(LIB, "Main.lean")]
    for root, _, names in os.walk(os.path.join(LIB, "Statements")):
        for n in sorted(names):
            if n.endswith(".lean"):
                files.append(os.path.join(root, n))
    rows = []
    for f in files:
        src = open(f, encoding="utf-8").read()
        code = strip_comments(src)
        ns = NS.search(code)
        ns = ns.group(1) if ns else ""
        rel = os.path.relpath(f, PROJ).replace("\\", "/")
        sorries = len(re.findall(r"\bsorry\b", code))
        open_banner = "-- OPEN" in src or "[OPEN]" in src
        for kind, name in DECL.findall(code):
            full = (ns + "." + name) if ns else name
            rows.append(dict(name=name, full=full, file=rel, kind=kind, sorries=sorries,
                             open=open_banner))
    return rows


def write_audit_lean(rows):
    lines = ["-- generated by lean/audit.py (A216); do not edit by hand",
             "import PackingCertMathlib.Main", "import PackingCertMathlib.Statements", ""]
    for r in rows:
        lines.append("#print axioms " + r["full"])
    os.makedirs(os.path.dirname(AUDIT_LEAN), exist_ok=True)
    open(AUDIT_LEAN, "w", encoding="utf-8").write("\n".join(lines) + "\n")


def run(cmd):
    t0 = time.time()
    p = subprocess.run(cmd, cwd=PROJ, capture_output=True, text=True, encoding="utf-8",
                       errors="replace")
    return p.returncode, p.stdout + p.stderr, time.time() - t0


def parse_axioms(out):
    # "'X' depends on axioms: [a,\n b]"  /  "'X' does not depend on any axioms"
    res = {}
    text = re.sub(r"\n\s+", " ", out)
    for m in re.finditer(r"'([^']+)' depends on axioms: \[([^\]]*)\]", text):
        res[m.group(1)] = [a.strip() for a in m.group(2).split(",") if a.strip()]
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", text):
        res[m.group(1)] = []
    return res


def short(ax):
    if ax in STD:
        return None
    m = re.match(r"(.*)\._native\.native_decide\.ax_\d+_\d+$", ax)
    if m:
        return "native_decide(" + m.group(1) + ")"
    return ax


def main():
    build = "--no-build" not in sys.argv
    rows = scan()
    write_audit_lean(rows)
    log = []
    if build:
        rc, out, dt = run([sys.executable, LAKEB, "PackingCertMathlib.Main",
                           "PackingCertMathlib.Statements"])
        log.append("build: exit %d in %.1f s" % (rc, dt))
        if rc != 0:
            print(out[-4000:])
            print("audit: build failed")
            return 1
    rc, out, dt = run([sys.executable, LAKEB, "--env", "scratch/Audit.lean"])
    log.append("audit run: exit %d in %.1f s" % (rc, dt))
    ax = parse_axioms(out)
    bad = 0
    md = ["# lean/AUDIT.md -- the readable layer, audited (A216)", "",
          "Generated by `lean/audit.py` on %s.  %s." % (time.strftime("%Y-%m-%d %H:%M"),
                                                       "; ".join(log)), "",
          "Legend: `std` = `propext, Classical.choice, Quot.sound`; `native_decide(f)` = the "
          "`Lean.ofReduceBool` evaluation of the compiled checker `f` on its certificate data; "
          "every other entry is a NAMED axiom of the project (see `Statements/Open/`).  `kind` "
          "is how the statement is declared in its file; a `theorem` whose axiom list names a "
          "project axiom is a restatement PROVED FROM that axiom.", "",
          "| statement | file | kind | depends on | sorry |", "|---|---|---|---|---|"]
    named = {}
    for r in rows:
        axs = ax.get(r["full"])
        if axs is None:
            dep = "(no output)"
            bad += 1
        else:
            extra = [s for s in (short(a) for a in axs) if s]
            dep = "std" + ("" if not extra else " + " + ", ".join(extra))
            for a in axs:
                s = short(a)
                if s and not s.startswith("native_decide("):
                    named.setdefault(s, []).append(r["name"])
            if "sorryAx" in axs:
                bad += 1
        srr = r["sorries"] + (1 if axs and "sorryAx" in axs else 0)
        md.append("| `%s` | `%s` | %s%s | %s | %d |" % (
            r["name"], r["file"], r["kind"], " (OPEN)" if r["open"] else "", dep, srr))
    md += ["", "## Named axioms in use", ""]
    for a in sorted(named):
        md.append("* `%s` -- used by: %s" % (a, ", ".join("`%s`" % n for n in named[a])))
    md += ["", "## Verdict", "",
           ("**%d statement(s) depend on `sorryAx` or produced no output.**" % bad) if bad
           else "**No statement depends on `sorryAx`.**  Every `theorem` above is proved from "
                "the listed axioms; every `axiom` is its own only non-standard dependence.", ""]
    open(AUDIT_MD, "w", encoding="utf-8").write("\n".join(md))
    print("\n".join(md))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
