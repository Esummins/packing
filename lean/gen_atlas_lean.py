#!/usr/bin/env python3
"""
gen_atlas_lean.py -- emit the A86 atlas-value data module for the PackingCert.Atlas
kernel (lean/PackingCertMathlib/PackingCertMathlib/AtlasKernel.lean).

  attempts/A86-lean-wave7/certs/atlas_lean/*.json
      (produced by attempts/A86-lean-wave7/code/emit_atlas_lean.py)
    -> lean/PackingCertMathlib/PackingCertMathlib/AtlasData.lean

`atlasAll` holds the boxes with L >= s0 = 969271/250000 (the (D') discharge boxes);
`atlasBelow` holds the rest (kept for the record, NOT discharge leaves).

Usage:  python lean/gen_atlas_lean.py [--certdir DIR] [--out PATH]

All numbers in the inputs are exact rational strings; floats are refused.
Rational literal convention matches lean/gen_rigidity_lean.py's rat_lean.
"""
from __future__ import annotations

import argparse
import json
from fractions import Fraction
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

DEF_CERTDIR = REPO / "attempts" / "A86-lean-wave7" / "certs" / "atlas_lean"
DEF_OUT = REPO / "lean" / "PackingCertMathlib" / "PackingCertMathlib" / "AtlasData.lean"

S0 = Fraction(969271, 250000)


def to_frac(v) -> Fraction:
    if isinstance(v, bool):
        raise ValueError("boolean is not a number")
    if isinstance(v, float):
        raise ValueError(f"float {v!r} in certificate: refuse (not exact)")
    if isinstance(v, (int, str)):
        return Fraction(str(v).strip())
    raise ValueError(f"cannot parse rational from {v!r}")


def rat_lean(q: Fraction) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : Rat)"
    return f"(({q.numerator} : Rat) / {q.denominator})"


def box_lean(b) -> str:
    return ("{ x0 := " + rat_lean(to_frac(b["x0"])) +
            ", x1 := " + rat_lean(to_frac(b["x1"])) +
            ", y0 := " + rat_lean(to_frac(b["y0"])) +
            ", y1 := " + rat_lean(to_frac(b["y1"])) +
            ", t0 := " + rat_lean(to_frac(b["t0"])) +
            ", t1 := " + rat_lean(to_frac(b["t1"])) + " }")


def wit_lean(w) -> str:
    for k in ("i1", "k1", "i2", "k2"):
        if isinstance(w[k], bool) or not isinstance(w[k], int) or w[k] < 0:
            raise ValueError(f"bad witness index {w!r}")
    if w["i1"] > 10 or w["i2"] > 10 or w["k1"] > 3 or w["k2"] > 3:
        raise ValueError(f"witness index out of range: {w!r}")
    ax = "true" if w["axisX"] else "false"
    return (f"{{ i1 := {w['i1']}, k1 := {w['k1']}, i2 := {w['i2']}, "
            f"k2 := {w['k2']}, axisX := {ax} }}")


def cert_lean(c) -> str:
    boxes = c["boxes"]
    if len(boxes) != 11:
        raise ValueError(f"{c['name']}: {len(boxes)} boxes, expected 11")
    wits = c["wits"]
    if not wits:
        raise ValueError(f"{c['name']}: no witnesses")
    lines = [f"def atlas_{c['name']} : AtlasCert := {{",
             f"  name := {json.dumps(c['name'])},",
             "  boxes := #[",
             ",\n".join("    " + box_lean(b) for b in boxes),
             "  ],",
             f"  L := {rat_lean(to_frac(c['L']))},",
             "  wits := #[",
             ",\n".join("    " + wit_lean(w) for w in wits),
             "  ] }"]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--certdir", type=Path, default=DEF_CERTDIR)
    ap.add_argument("--out", type=Path, default=DEF_OUT)
    args = ap.parse_args()

    files = sorted(args.certdir.glob("*.json"))
    if not files:
        raise SystemExit(f"no certificates under {args.certdir}")
    certs = [json.loads(f.read_text()) for f in files]
    # deterministic order: atlas families first (file order), then ghosts
    certs.sort(key=lambda c: (c["provenance"]["kind"] != "atlas", c["name"]))

    above = [c for c in certs if to_frac(c["L"]) >= S0]
    below = [c for c in certs if to_frac(c["L"]) < S0]

    out = ["import PackingCertMathlib.AtlasKernel", "",
           "/-! GENERATED by lean/gen_atlas_lean.py from",
           "    attempts/A86-lean-wave7/certs/atlas_lean/*.json "
           f"({len(certs)} boxes: {len(above)} with L >= s0, {len(below)} below) --",
           "    do not edit.  Sources: A37 `atlas_final.json` (37 critical-point boxes) and",
           "    A85 `cp85_k0_search.json` (the 12 k0 ghosts within 0.02 of s0).",
           "    Angle convention: theta folded by the extent-preserving triangle wave",
           "    g(theta) = min(theta mod pi/2, pi/2 - theta mod pi/2) into [0, pi/4], then",
           "    t = tan(theta/2) with outward rational rounding onto the 1e-12 grid. -/", "",
           "set_option maxRecDepth 8000", "",
           "namespace PackingCert.Atlas.Data", "",
           "open PackingCert.Atlas", ""]
    for c in certs:
        out.append(cert_lean(c))
        out.append("")
    out.append("/-- The atlas discharge boxes: `L >= s0 = 969271/250000`. -/")
    out.append("def atlasAll : Array AtlasCert := #[")
    out.append(",\n".join("  atlas_" + c["name"] for c in above))
    out.append("]")
    out.append("")
    out.append("/-- Boxes whose recomputed extent bound falls short of `s0` "
               "(NOT discharge leaves). -/")
    out.append("def atlasBelow : Array AtlasCert := #[")
    out.append(",\n".join("  atlas_" + c["name"] for c in below))
    out.append("]")
    out.append("")
    out.append("end PackingCert.Atlas.Data")
    out.append("")
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {args.out}  ({len(certs)} certs, {len(above)} in atlasAll, "
          f"{len(below)} in atlasBelow)")


if __name__ == "__main__":
    main()
