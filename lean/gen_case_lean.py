#!/usr/bin/env python3
"""
gen_case_lean.py -- convert a case-LP certificate JSON (format of verify_case.py,
frozen spec docs/specs/case_lp_certificate_v1.md) into Lean source for the
PackingCert.CaseI.checkCaseI checker (lean/PackingCertMathlib/.../CaseChecker.lean).

Usage:
    python lean/gen_case_lean.py CERT.json --depth 44 --name k5_06_lo \
        [-o lean/PackingCertMathlib/PackingCertMathlib/CaseData506.lean]

Integer scaling identical to verify_case.py's Verifier.__init__ (A70): atoms sorted
heavy-first, PD = lcm of the atom's two denominators, WD = lcm of all weight
denominators, WI = w * WD; cores/nofams emitted as exact Rat literals.  D4 symmetry
expansion as in the loader (distinct orbit images only).
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from fractions import Fraction
from pathlib import Path


def to_frac(v) -> Fraction:
    if isinstance(v, bool):
        raise ValueError("boolean is not a number")
    if isinstance(v, int):
        return Fraction(v)
    if isinstance(v, float):
        raise ValueError(f"float {v!r} in certificate: refuse (not exact)")
    if isinstance(v, str):
        return Fraction(v.strip())
    raise ValueError(f"cannot parse rational from {v!r}")


def rat_lean(q: Fraction) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : Rat)"
    return f"(({q.numerator} : Rat) / {q.denominator})"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cert")
    ap.add_argument("--depth", type=int, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    d = json.loads(Path(a.cert).read_text(encoding="utf-8"))
    s = to_frac(d["s"])
    n = int(d.get("n", 11))
    raw = d["atoms"]
    atoms, weights = [], []
    if raw and isinstance(raw[0], dict):
        for at in raw:
            atoms.append((to_frac(at["x"]), to_frac(at["y"])))
            weights.append(to_frac(at["w"]))
    else:
        ws = d["weights"]
        assert len(ws) == len(raw)
        for (x, y), w in zip(raw, ws):
            atoms.append((to_frac(x), to_frac(y)))
            weights.append(to_frac(w))
    if d.get("symmetry"):
        assert str(d["symmetry"]).upper() == "D4"
        ex_a, ex_w = [], []
        for (x, y), w in zip(atoms, weights):
            seen = []
            for q in [(x, y), (s - x, y), (x, s - y), (s - x, s - y),
                      (y, x), (s - y, x), (y, s - x), (s - y, s - x)]:
                if q not in seen:
                    seen.append(q)
            for q in seen:
                ex_a.append(q)
                ex_w.append(w)
        atoms, weights = ex_a, ex_w
    for w in weights:
        assert w >= 0, "negative weight"

    hyp = d.get("hypotheses", {}) or {}
    cores = [(to_frac(c["kx"]), to_frac(c["ky"]), to_frac(c["tm"]), to_frac(c["a"]))
             for c in hyp.get("cores", [])]
    nofams = [(to_frac(f["x0"]), to_frac(f["x1"]), to_frac(f["y0"]), to_frac(f["y1"]),
               [(to_frac(t0), to_frac(t1)) for t0, t1 in f["t_intervals"]])
              for f in hyp.get("nofams", [])]
    budget = int(d.get("budget", n))
    assert budget == n - len(cores), "budget != n - #cores"

    # heavy atoms first (Verifier ordering)
    order = sorted(range(len(atoms)), key=lambda i: -weights[i])
    atoms = [atoms[i] for i in order]
    weights = [weights[i] for i in order]

    wd = 1
    for w in weights:
        wd = wd * w.denominator // math.gcd(wd, w.denominator)
    lines = []
    for (px, py), w in zip(atoms, weights):
        pd = px.denominator * py.denominator // math.gcd(px.denominator, py.denominator)
        wi = w.numerator * (wd // w.denominator)
        lines.append(f"  ⟨{px.numerator * (pd // px.denominator)}, "
                     f"{py.numerator * (pd // py.denominator)}, {pd}, {wi}⟩")

    core_lines = [f"  ⟨{rat_lean(kx)}, {rat_lean(ky)}, {rat_lean(tm)}, {rat_lean(av)}⟩"
                  for kx, ky, tm, av in cores]
    fam_lines = []
    for x0, x1, y0, y1, tivs in nofams:
        tl = ", ".join(f"({rat_lean(t0)}, {rat_lean(t1)})" for t0, t1 in tivs)
        fam_lines.append(f"  ⟨{rat_lean(x0)}, {rat_lean(x1)}, {rat_lean(y0)}, "
                         f"{rat_lean(y1)}, [{tl}]⟩")

    out = []
    out.append("import PackingCertMathlib.CaseChecker\n")
    out.append(f"/-!\nAuto-generated by `lean/gen_case_lean.py` from `{a.cert}`"
               f" (depth {a.depth}).\nDo not edit by hand.\n-/\n")
    out.append("namespace PackingCert.CaseI.Data\n")
    out.append(f"def {a.name} : CCertI := {{")
    out.append(f"  n := {n}")
    out.append(f"  sNum := {s.numerator}")
    out.append(f"  sDen := {s.denominator}")
    out.append(f"  wd := {wd}")
    out.append(f"  depth := {a.depth}")
    out.append("  atoms := [")
    out.append(",\n".join(lines))
    out.append("  ]")
    out.append("  cores := [")
    out.append(",\n".join(core_lines))
    out.append("  ]")
    out.append("  nofams := [" + (",\n".join(fam_lines) if fam_lines else "") + "] }")
    out.append("")
    out.append(f"end PackingCert.CaseI.Data")
    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {a.out}: {len(atoms)} atoms, {len(cores)} cores, "
          f"{len(nofams)} nofams, wd = {wd}, budget = {budget}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
