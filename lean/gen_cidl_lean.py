#!/usr/bin/env python3
"""gen_cidl_lean.py -- emit PackingCertMathlib/CidlData.lean from certs/cidl_identity.json.

The generated module contains ONLY the certificate's own data (the octic coefficient
list as recorded in the JSON, the univariate coefficient lists of `e` and `Delta`, and
the 13 bivariate cofactors q_j(t, S) in the ROWSPEC order of certs/verify_cidl.py).
The 13 GENERATORS are NOT emitted here: they are rebuilt from the A22 corner/edge
conventions inside `CidlGen.lean`, exactly as `verify_cidl.py` rebuilds them.

Usage:  python lean/gen_cidl_lean.py
"""
import hashlib
import json
import os
import sys
from fractions import Fraction as F

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CERT = os.path.join(REPO, "certs", "cidl_identity.json")
OUT = os.path.join(REPO, "lean", "PackingCertMathlib", "PackingCertMathlib", "CidlData.lean")

# ROWSPEC order of certs/verify_cidl.py (the cofactor keys)
NAMES = [
    'E1c2-8e3', 'E2c3-8e0', 'E3c2-7e3', 'E4c1-7e2', 'E4c2-6e3', 'E5c0-9e1',
    'E6c1-9e2', 'W6c2[y=s]', 'E7c1-8e2', 'E7c2-9e3', 'E8c2-10e3', 'E9c1-10e2',
    'W10c1[x=s]',
]


def int_of(s):
    v = F(s)
    if v.denominator != 1:
        raise SystemExit("non-integer coefficient in certificate: %s" % s)
    return v.numerator


def lean_int_list(xs, per_line=8):
    if not xs:
        return "[]"
    out = []
    for i in range(0, len(xs), per_line):
        out.append(", ".join(str(v) for v in xs[i:i + per_line]))
    return "[" + (",\n   ".join(out)) + "]"


def main():
    raw = open(CERT, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    cert = json.loads(raw.decode())

    oct_c = [int_of(x) for x in cert['octic']['coefficients_low_to_high']]
    e_c = [int_of(x) for x in cert['e']['coefficients_low_to_high']]
    d_c = [int_of(x) for x in cert['Delta']['coefficients_low_to_high']]
    cof = cert['cofactors']
    if sorted(cof) != sorted(NAMES):
        raise SystemExit("cofactor keys do not match ROWSPEC")

    L = []
    A = L.append
    A("import PackingCertMathlib.CidlPoly")
    A("")
    A("/-")
    A("  AUTOGENERATED by `lean/gen_cidl_lean.py` -- DO NOT EDIT BY HAND.")
    A("")
    A("  Source certificate: certs/cidl_identity.json")
    A("  format:  %s" % cert.get('format'))
    A("  sha256:  %s" % sha)
    A("")
    A("  Contents: the certificate's octic coefficient list, the univariate coefficient")
    A("  lists of `e` (deg %d) and `Delta` (deg %d), and the 13 bivariate cofactors"
      % (len(e_c) - 1, len(d_c) - 1))
    A("  q_j(t, S) in the ROWSPEC order of `certs/verify_cidl.py`.  All coefficients are")
    A("  integers in the certificate; they are stored as `Int` and cast to `Rat` by")
    A("  `CidlPoly.uniToPoly` / `CidlPoly.bivToPoly`.")
    A("-/")
    A("set_option maxHeartbeats 1000000")
    A("")
    A("namespace PackingCert")
    A("namespace Cidl")
    A("namespace Data")
    A("")
    A("/-- The octic coefficient list AS RECORDED IN THE CERTIFICATE (low to high).")
    A("`CidlCheck.cidl_octic_canonical` checks it against the canonical Trump octic. -/")
    A("def certOctic : List Int :=")
    A("  " + lean_int_list(oct_c))
    A("")
    A("/-- `e(t)`, the certificate's univariate saturation factor (low to high). -/")
    A("def eC : List Int :=")
    A("  " + lean_int_list(e_c))
    A("")
    A("/-- `Delta(t)`, the 12x12 system determinant (low to high). -/")
    A("def deltaC : List Int :=")
    A("  " + lean_int_list(d_c))
    A("")

    defs = []
    for idx, nm in enumerate(NAMES):
        dn = "cofRaw%02d" % idx
        defs.append(dn)
        A("/-- Cofactor `q_%d` for generator `%s`, as (S-power, t-coefficients low to high). -/"
          % (idx, nm))
        # one def per (S-power, t-coefficient list): a single ~300-element list literal
        # elaborates in well under a second, while a 2400-element nested literal blows
        # through maxHeartbeats (the elaborator's cost is superlinear in literal size).
        parts = []
        for ti, term in enumerate(cof[nm]):
            k = int(term['spow'])
            cs = [int_of(x) for x in term['t']]
            A("def %s_%d : List Int :=" % (dn, ti))
            A("  " + lean_int_list(cs))
            parts.append("(%d, %s_%d)" % (k, dn, ti))
        A("def %s : List (Nat × List Int) :=" % dn)
        A("  [" + ", ".join(parts) + "]")
        A("")

    A("/-- The 13 cofactors as `Poly` values, in ROWSPEC order:")
    for idx, nm in enumerate(NAMES):
        A("  %2d  %s" % (idx, nm))
    A("-/")
    A("def cofs : List Poly :=")
    A("  [" + ",\n   ".join("bivToPoly %s" % d for d in defs) + "]")
    A("")
    A("end Data")
    A("end Cidl")
    A("end PackingCert")

    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("wrote %s (%d bytes), cert sha256 %s" % (OUT, os.path.getsize(OUT), sha))


if __name__ == '__main__':
    sys.exit(main())
