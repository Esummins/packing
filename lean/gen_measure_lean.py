#!/usr/bin/env python3
"""
gen_measure_lean.py -- convert a MEASURE certificate JSON (format of certs/verify_measure.py,
attempt A08) into Lean source for the PackingCert.Measure checker.

Usage
-----
    python lean/gen_measure_lean.py CERT.json --fuel 40 [--name a05_10pt]
        [-o lean/PackingCert/PackingCert/MeasureData.lean]

Input format (same as certs/verify_measure.py):
    {"s": "1870797/500000", "n": 11,
     "atoms": [["x","y"], ...]  or  [{"x":..,"y":..,"w":..}, ...],
     "weights": ["w", ...],                (if atoms are pairs)
     "symmetry": "D4"                      (optional: expand each atom to its D4 orbit in [0,s]^2,
                                            distinct images only, each with the listed weight)
     ...}
All numbers must be exact (strings "p/q" or decimal strings, or ints); floats are rejected.

Output: `def <name> : MCert := { n := .., side := .., fuel := .., atoms := [⟨px, py, w⟩, ...] }`
in namespace PackingCert.Measure.Data.  Rationals are emitted as `(p : Rat) / q`.

The Lean checker's semantics (see PackingCert/Measure.lean):
  every closed unit square Q inside the closed container [0,s]^2 has mu(Q) >= 1, total mass < n,
  all weights >= 0; established by interval branch-and-bound over (t, cx, cy) to depth `fuel`.
`fuel` is the max bisection depth; verify_measure.py's report gives "max_depth" -- use a few more.
"""
from __future__ import annotations

import argparse
import json
import sys
from fractions import Fraction
from pathlib import Path


def to_frac(v) -> Fraction:
    if isinstance(v, bool):
        raise ValueError("boolean is not a number")
    if isinstance(v, int):
        return Fraction(v)
    if isinstance(v, float):
        raise ValueError(f"float {v!r} in certificate: refuse (not exact)")
    if isinstance(v, str):
        return Fraction(v.strip())
    if isinstance(v, dict) and "num" in v and "den" in v:
        return Fraction(int(v["num"]), int(v["den"]))
    raise ValueError(f"cannot parse rational from {v!r}")


def d4_orbit(p, s):
    x, y = p
    imgs = [(x, y), (s - x, y), (x, s - y), (s - x, s - y),
            (y, x), (s - y, x), (y, s - x), (s - y, s - x)]
    out = []
    for q in imgs:
        if q not in out:
            out.append(q)
    return out


def rat_lean(q: Fraction) -> str:
    if q.denominator == 1:
        return f"({q.numerator} : Rat)"
    return f"(({q.numerator} : Rat) / {q.denominator})"


def load(path: Path):
    cert = json.loads(path.read_text(encoding="utf-8"))
    s = to_frac(cert["s"])
    n = int(cert.get("n", 11))
    raw = cert["atoms"]
    atoms = []
    if raw and isinstance(raw[0], dict):
        for a in raw:
            atoms.append((to_frac(a["x"]), to_frac(a["y"]), to_frac(a["w"])))
    else:
        weights = cert["weights"]
        if len(weights) != len(raw):
            raise ValueError("weights/atoms length mismatch")
        for (x, y), w in zip(raw, weights):
            atoms.append((to_frac(x), to_frac(y), to_frac(w)))
    if cert.get("symmetry") == "D4":
        exp = []
        for x, y, w in atoms:
            for q in d4_orbit((x, y), s):
                exp.append((q[0], q[1], w))
        atoms = exp
    return s, n, atoms, cert


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("json", type=Path)
    ap.add_argument("--fuel", type=int, required=True, help="max bisection depth")
    ap.add_argument("--name", default="mcert")
    ap.add_argument("-o", "--out", type=Path,
                    default=Path(__file__).resolve().parent / "PackingCert" / "PackingCert" / "MeasureData.lean")
    args = ap.parse_args(argv)

    s, n, atoms, raw = load(args.json)
    total = sum(w for _, _, w in atoms)
    if any(w < 0 for _, _, w in atoms):
        print("[gen_measure_lean] negative weight -> invalid"); return 1
    if total >= n:
        print(f"[gen_measure_lean] total mass {total} >= n = {n} -> invalid"); return 1
    print(f"[gen_measure_lean] {args.json}: s = {s} (= {float(s):.7f}), n = {n}, "
          f"{len(atoms)} atoms (after symmetry expansion), total mass = {total} (= {float(total):.6f})")
    src = str(args.json).replace("\\", "/")
    lines = [
        "import PackingCert.Measure",
        "",
        "/-!",
        f"# Measure certificate data: `{args.name}`",
        "",
        "AUTO-GENERATED by lean/gen_measure_lean.py -- do not edit by hand.",
        f"Source: {src}",
        f"s = {s.numerator}/{s.denominator} (= {float(s):.7f}), n = {n}, atoms = {len(atoms)}, "
        f"total mass = {total.numerator}/{total.denominator}, fuel = {args.fuel}",
        "-/",
        "",
        "namespace PackingCert.Measure.Data",
        "",
        f"def {args.name} : MCert :=",
        f"  {{ n := {n}",
        f"    side := {rat_lean(s)}",
        f"    fuel := {args.fuel}",
        "    atoms :=",
    ]
    body = ",\n".join(f"        ⟨{rat_lean(x)}, {rat_lean(y)}, {rat_lean(w)}⟩" for x, y, w in atoms)
    lines.append("      [ " + body.lstrip() + " ] }")
    lines += ["", "end PackingCert.Measure.Data", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"[gen_measure_lean] wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
